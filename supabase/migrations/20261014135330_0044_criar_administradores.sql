CREATE TABLE IF NOT EXISTS public.t_admin (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario_pai bigint NOT NULL UNIQUE
    REFERENCES public.t_usuario_pai(id)
    ON DELETE CASCADE,
  ativo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.t_admin ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "own admin select" ON public.t_admin;

CREATE POLICY "own admin select"
ON public.t_admin
FOR SELECT
TO authenticated
USING (id_usuario_pai = public.current_pai_id());

REVOKE ALL ON public.t_admin FROM anon;
REVOKE INSERT, UPDATE, DELETE ON public.t_admin FROM authenticated;
GRANT SELECT ON public.t_admin TO authenticated;

INSERT INTO public.t_admin (id_usuario_pai, ativo)
