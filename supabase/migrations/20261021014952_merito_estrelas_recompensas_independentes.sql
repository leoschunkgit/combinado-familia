create or replace function public.registrar_concessao_estrela_ocorrencia()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_pai_id bigint;
  v_filho_id bigint;
  v_vigencia_id bigint;
  v_tarefa_id bigint;
  v_tarefa_nome text;
  v_data date;
begin
  if new.tipo <> 'FEZ' then
    return new;
  end if;

  select
    ft.id_usuario_pai,
    ft.id_filho,
    ft.id_vigencia,
    ft.id_tarefa,
    t.nome
  into
    v_pai_id,
    v_filho_id,
    v_vigencia_id,
    v_tarefa_id,
    v_tarefa_nome
  from public.t_filho_tarefa ft
  left join public.t_tarefa t
    on t.id = ft.id_tarefa
   and t.id_usuario_pai = ft.id_usuario_pai
  where ft.id = new.id_filho_tarefa
    and ft.id_usuario_pai = new.id_usuario_pai;

  if v_pai_id is null
     or v_filho_id is null
     or v_vigencia_id is null
     or v_tarefa_id is null then
    return new;
  end if;

  v_data := timezone('America/Sao_Paulo', new.created_at)::date;

  insert into public.t_estrela_concessao (
    id_usuario_pai,
    id_filho,
    id_vigencia,
    id_tarefa,
    id_filho_tarefa_origem,
    id_ocorrencia_origem,
    tarefa_nome_snapshot,
    data_referencia,
    created_at
  )
  values (
    v_pai_id,
    v_filho_id,
    v_vigencia_id,
    v_tarefa_id,
    new.id_filho_tarefa,
    new.id,
    v_tarefa_nome,
    v_data,
    now()
  )
  on conflict do nothing;

  return new;
end;
$function$;

drop trigger if exists trg_movimento_estrela_ocorrencia on public.t_ocorrencia;
drop trigger if exists trg_concessao_estrela_ocorrencia on public.t_ocorrencia;

create trigger trg_concessao_estrela_ocorrencia
after insert or update of tipo, id_filho_tarefa, created_at
on public.t_ocorrencia
for each row
execute function public.registrar_concessao_estrela_ocorrencia();

create or replace function public.resumo_estrelas_filho_interno(
  p_id_usuario_pai bigint,
  p_id_filho bigint
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $function$
declare
  v_total integer;
  v_hoje integer;
  v_vigencia_id bigint;
  v_vigencia integer;
  v_recompensas jsonb;
  v_resgates jsonb;
begin
  if not exists (
    select 1
    from public.t_filho f
    where f.id = p_id_filho
      and f.id_usuario_pai = p_id_usuario_pai
  ) then
    return null;
  end if;

  v_total := public.estrelas_total_conquistado_interno(
    p_id_usuario_pai,
    p_id_filho
  );

  select count(*)::integer
    into v_hoje
  from public.t_estrela_concessao c
  where c.id_usuario_pai = p_id_usuario_pai
    and c.id_filho = p_id_filho
    and c.data_referencia = timezone('America/Sao_Paulo', now())::date;

  select v.id
    into v_vigencia_id
  from public.t_vigencia v
  where v.id_usuario_pai = p_id_usuario_pai
    and now() between v.data_inicio and v.data_fim
    and exists (
      select 1
      from public.t_filho_tarefa ft
      where ft.id_usuario_pai = p_id_usuario_pai
        and ft.id_filho = p_id_filho
        and ft.id_vigencia = v.id
    )
  order by v.data_inicio desc
  limit 1;

  if v_vigencia_id is null then
    v_vigencia := 0;
  else
    select count(*)::integer
      into v_vigencia
    from public.t_estrela_concessao c
    where c.id_usuario_pai = p_id_usuario_pai
      and c.id_filho = p_id_filho
      and c.id_vigencia = v_vigencia_id;
  end if;

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'id', r.id,
        'nome', r.nome,
        'descricao', r.descricao,
        'estrelas_necessarias', r.estrelas_necessarias,
        'progresso', x.progresso,
        'faltam', greatest(r.estrelas_necessarias - x.progresso, 0),
        'disponivel', (not x.tem_pendente and x.progresso >= r.estrelas_necessarias),
        'pendente', x.tem_pendente,
        'marco_estrelas', x.marco_estrelas
      )
      order by r.estrelas_necessarias, r.nome
    ),
    '[]'::jsonb
  )
  into v_recompensas
  from public.t_recompensa_estrela r
  cross join lateral (
    select
      greatest(
        v_total - coalesce((
          select rr.total_estrelas_no_resgate
          from public.t_recompensa_resgate rr
          where rr.id_usuario_pai = p_id_usuario_pai
            and rr.id_filho = p_id_filho
            and rr.id_recompensa = r.id
            and rr.status = 'ENTREGUE'
            and rr.total_estrelas_no_resgate is not null
          order by rr.entregue_em desc nulls last, rr.id desc
          limit 1
        ), 0),
        0
      )::integer as progresso,
      coalesce((
        select rr.total_estrelas_no_resgate
        from public.t_recompensa_resgate rr
        where rr.id_usuario_pai = p_id_usuario_pai
          and rr.id_filho = p_id_filho
          and rr.id_recompensa = r.id
          and rr.status = 'ENTREGUE'
          and rr.total_estrelas_no_resgate is not null
        order by rr.entregue_em desc nulls last, rr.id desc
        limit 1
      ), 0)::integer as marco_estrelas,
      exists (
        select 1
        from public.t_recompensa_resgate rr
        where rr.id_usuario_pai = p_id_usuario_pai
          and rr.id_filho = p_id_filho
          and rr.id_recompensa = r.id
          and rr.status = 'PENDENTE'
      ) as tem_pendente
  ) x
  where r.id_usuario_pai = p_id_usuario_pai
    and r.id_filho = p_id_filho
    and r.ativo = true;

  select coalesce(jsonb_agg(x.item order by x.ordem desc), '[]'::jsonb)
    into v_resgates
  from (
    select
      rr.created_at as ordem,
      jsonb_build_object(
        'id', rr.id,
        'id_recompensa', rr.id_recompensa,
        'recompensa_nome', rr.recompensa_nome,
        'estrelas_utilizadas', rr.estrelas_utilizadas,
        'meta_estrelas_no_resgate', coalesce(rr.meta_estrelas_no_resgate, rr.estrelas_utilizadas),
        'total_estrelas_no_resgate', rr.total_estrelas_no_resgate,
        'status', rr.status,
        'created_at', rr.created_at,
        'entregue_em', rr.entregue_em,
        'cancelado_em', rr.cancelado_em
      ) as item
    from public.t_recompensa_resgate rr
    where rr.id_usuario_pai = p_id_usuario_pai
      and rr.id_filho = p_id_filho
    order by rr.created_at desc
    limit 20
  ) x;

  return jsonb_build_object(
    'hoje', v_hoje,
    'vigencia_atual', v_vigencia,
    'saldo', v_total,
    'total_conquistado', v_total,
    'recompensas', v_recompensas,
    'resgates', v_resgates
  );
end;
$function$;

create or replace function public.resgatar_recompensa_estrelas(
  p_id_recompensa bigint
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_pai_id bigint;
  v_filho_id bigint;
  v_nome text;
  v_meta integer;
  v_total integer;
  v_marco integer;
  v_progresso integer;
  v_resgate_id bigint;
begin
  select p.id
    into v_pai_id
  from public.t_usuario_pai p
  where p.auth_user_id = auth.uid();

  if v_pai_id is null then
    raise exception 'Responsável não encontrado';
  end if;

  select r.id_filho, r.nome, r.estrelas_necessarias
    into v_filho_id, v_nome, v_meta
  from public.t_recompensa_estrela r
  where r.id = p_id_recompensa
    and r.id_usuario_pai = v_pai_id
    and r.ativo = true;

  if v_filho_id is null then
    raise exception 'Recompensa não encontrada ou inativa';
  end if;

  perform 1
  from public.t_filho f
  where f.id = v_filho_id
    and f.id_usuario_pai = v_pai_id
  for update;

  if exists (
    select 1
    from public.t_recompensa_resgate rr
    where rr.id_usuario_pai = v_pai_id
      and rr.id_filho = v_filho_id
      and rr.id_recompensa = p_id_recompensa
      and rr.status = 'PENDENTE'
  ) then
    raise exception 'Esta recompensa já possui um resgate aguardando entrega';
  end if;

  v_total := public.estrelas_total_conquistado_interno(v_pai_id, v_filho_id);

  select coalesce((
    select rr.total_estrelas_no_resgate
    from public.t_recompensa_resgate rr
    where rr.id_usuario_pai = v_pai_id
      and rr.id_filho = v_filho_id
      and rr.id_recompensa = p_id_recompensa
      and rr.status = 'ENTREGUE'
      and rr.total_estrelas_no_resgate is not null
    order by rr.entregue_em desc nulls last, rr.id desc
    limit 1
  ), 0)
  into v_marco;

  v_progresso := greatest(v_total - v_marco, 0);

  if v_progresso < v_meta then
    raise exception 'Esta recompensa ainda não atingiu a quantidade necessária de estrelas';
  end if;

  insert into public.t_recompensa_resgate (
    id_usuario_pai,
    id_filho,
    id_recompensa,
    recompensa_nome,
    estrelas_utilizadas,
    meta_estrelas_no_resgate,
    total_estrelas_no_resgate,
    status
  )
  values (
    v_pai_id,
    v_filho_id,
    p_id_recompensa,
    v_nome,
    v_meta,
    v_meta,
    v_total,
    'PENDENTE'
  )
  returning id into v_resgate_id;

  return v_resgate_id;
end;
$function$;

create or replace function public.alterar_status_resgate_estrelas(
  p_id_resgate bigint,
  p_status text
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_pai_id bigint;
  v_filho_id bigint;
  v_status_atual text;
begin
  select p.id
    into v_pai_id
  from public.t_usuario_pai p
  where p.auth_user_id = auth.uid();

  if v_pai_id is null then
    raise exception 'Responsável não encontrado';
  end if;

  if p_status not in ('ENTREGUE', 'CANCELADO') then
    raise exception 'Status de resgate inválido';
  end if;

  select rr.id_filho, rr.status
    into v_filho_id, v_status_atual
  from public.t_recompensa_resgate rr
  where rr.id = p_id_resgate
    and rr.id_usuario_pai = v_pai_id
  for update;

  if v_filho_id is null then
    raise exception 'Resgate não encontrado';
  end if;

  perform 1
  from public.t_filho f
  where f.id = v_filho_id
    and f.id_usuario_pai = v_pai_id
  for update;

  if p_status = 'ENTREGUE' then
    if v_status_atual = 'CANCELADO' then
      raise exception 'Resgate cancelado não pode ser marcado como entregue';
    end if;

    if v_status_atual = 'ENTREGUE' then
      return true;
    end if;

    update public.t_recompensa_resgate
    set status = 'ENTREGUE',
        entregue_em = coalesce(entregue_em, now()),
        updated_at = now()
    where id = p_id_resgate
      and id_usuario_pai = v_pai_id;

    return true;
  end if;

  if v_status_atual = 'ENTREGUE' then
    raise exception 'Resgate entregue não pode ser cancelado';
  end if;

  if v_status_atual = 'CANCELADO' then
    return true;
  end if;

  update public.t_recompensa_resgate
  set status = 'CANCELADO',
      cancelado_em = coalesce(cancelado_em, now()),
      updated_at = now()
  where id = p_id_resgate
    and id_usuario_pai = v_pai_id;

  return true;
end;
$function$;

