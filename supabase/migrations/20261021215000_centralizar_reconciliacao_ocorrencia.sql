-- Núcleo transacional único de Fez / Não fez.
-- Primeiro passo da nova arquitetura: centraliza efeitos e auditoria sem alterar telas ainda.

create table if not exists public.t_ocorrencia_consequencia (
  id bigint generated by default as identity primary key,
  id_usuario_pai bigint not null references public.t_usuario_pai(id) on delete cascade,
  id_ocorrencia bigint not null unique references public.t_ocorrencia(id) on delete cascade,
  tipo text not null check (tipo in ('DESCONTO','PENALIDADE')),
  desconto_valor numeric null check (desconto_valor is null or desconto_valor > 0),
  penalidade_descricao text null,
  status text not null check (status in ('APLICADO','PENDENTE','CUMPRIDA','CANCELADA','ESTORNADO')),
  cumprida_em timestamptz null,
  cancelada_em timestamptz null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint t_ocorrencia_consequencia_coerencia_chk check (
    (
      tipo = 'DESCONTO'
      and desconto_valor is not null
      and penalidade_descricao is null
      and status in ('APLICADO','ESTORNADO')
      and cumprida_em is null
    )
    or
    (
      tipo = 'PENALIDADE'
      and desconto_valor is null
      and penalidade_descricao is not null
      and char_length(btrim(penalidade_descricao)) between 2 and 200
      and status in ('PENDENTE','CUMPRIDA','CANCELADA')
    )
  )
);

create index if not exists idx_ocorrencia_consequencia_pai
  on public.t_ocorrencia_consequencia (id_usuario_pai);
create index if not exists idx_ocorrencia_consequencia_status
  on public.t_ocorrencia_consequencia (id_usuario_pai, status);

alter table public.t_ocorrencia_consequencia enable row level security;

drop policy if exists ocorrencia_consequencia_select_own on public.t_ocorrencia_consequencia;
create policy ocorrencia_consequencia_select_own
on public.t_ocorrencia_consequencia
for select
using (id_usuario_pai = public.current_pai_id());

create table if not exists public.t_ocorrencia_reconciliacao (
  id bigint generated by default as identity primary key,
  id_usuario_pai bigint not null references public.t_usuario_pai(id) on delete cascade,
  id_ocorrencia bigint null,
  id_filho_tarefa bigint not null,
  acao text not null check (acao in ('CRIAR','ALTERAR','DESFAZER','CUMPRIR_PENALIDADE','RESOLVER_REVISAO')),
  origem text not null default 'RESPONSAVEL' check (origem in ('RESPONSAVEL','REVISAO','SISTEMA')),
  id_revisao bigint null,
  estado_anterior jsonb null,
  estado_novo jsonb null,
  motivo text null,
  created_at timestamptz not null default now()
);

create index if not exists idx_ocorrencia_reconciliacao_pai_data
  on public.t_ocorrencia_reconciliacao (id_usuario_pai, created_at desc);
create index if not exists idx_ocorrencia_reconciliacao_ocorrencia
  on public.t_ocorrencia_reconciliacao (id_ocorrencia);

alter table public.t_ocorrencia_reconciliacao enable row level security;

drop policy if exists ocorrencia_reconciliacao_select_own on public.t_ocorrencia_reconciliacao;
create policy ocorrencia_reconciliacao_select_own
on public.t_ocorrencia_reconciliacao
for select
using (id_usuario_pai = public.current_pai_id());

create or replace function public.contar_nao_fez_filho_vigencia(
  p_id_filho bigint,
  p_id_vigencia bigint
)
returns integer
language sql
stable
security definer
set search_path = ''
as $$
  select count(*)::integer
  from public.t_ocorrencia o
  join public.t_filho_tarefa ft
    on ft.id = o.id_filho_tarefa
   and ft.id_usuario_pai = o.id_usuario_pai
  where o.id_usuario_pai = public.current_pai_id()
    and ft.id_filho = p_id_filho
    and ft.id_vigencia = p_id_vigencia
    and o.tipo = 'NAO_FEZ';
$$;

-- Durante a transição, o fluxo legado continua como está.
-- Somente chamadas vindas do reconciliador ignoram a trava antiga.
create or replace function public.guard_nao_fez_limit()
returns trigger
language plpgsql
set search_path = 'public'
as $$
declare
  v_id_filho bigint;
  v_id_vigencia bigint;
  v_limite integer;
  v_tem_mesada boolean;
  v_total integer;
begin
  if current_setting('app.reconciliador_ocorrencia', true) = 'on' then
    return new;
  end if;

  if new.tipo <> 'NAO_FEZ' then return new; end if;

  select ft.id_filho, ft.id_vigencia, v.qtd_ocorrencia,
         coalesce(f.tem_mesada_opcional, false) and f.valor_mesada is not null
    into v_id_filho, v_id_vigencia, v_limite, v_tem_mesada
  from public.t_filho_tarefa ft
  join public.t_vigencia v on v.id = ft.id_vigencia
  join public.t_filho f on f.id = ft.id_filho
  where ft.id = new.id_filho_tarefa;

  if v_id_filho is null then raise exception 'Atribuição não encontrada'; end if;
  if v_tem_mesada then return new; end if;

  select count(*)::integer into v_total
  from public.t_ocorrencia o
  join public.t_filho_tarefa ft on ft.id = o.id_filho_tarefa
  where ft.id_filho = v_id_filho
    and ft.id_vigencia = v_id_vigencia
    and o.tipo = 'NAO_FEZ'
    and (tg_op <> 'UPDATE' or o.id <> old.id);

  if v_total >= v_limite then
    raise exception 'O limite de Não fez desta vigência já foi atingido';
  end if;

  return new;
end;
$$;

create or replace function public.recalcular_penalidade_por_ocorrencia_trigger()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_vigencia_antiga bigint;
  v_vigencia_nova bigint;
begin
  if current_setting('app.reconciliador_ocorrencia', true) = 'on' then
    return case when tg_op = 'DELETE' then old else new end;
  end if;

  if tg_op in ('UPDATE', 'DELETE') then
    select ft.id_vigencia into v_vigencia_antiga
    from public.t_filho_tarefa ft where ft.id = old.id_filho_tarefa;
  end if;

  if tg_op in ('INSERT', 'UPDATE') then
    select ft.id_vigencia into v_vigencia_nova
    from public.t_filho_tarefa ft where ft.id = new.id_filho_tarefa;
  end if;

  if v_vigencia_antiga is not null then
    perform public.recalcular_penalidade_vigencia(v_vigencia_antiga);
  end if;

  if v_vigencia_nova is not null
     and v_vigencia_nova is distinct from v_vigencia_antiga then
    perform public.recalcular_penalidade_vigencia(v_vigencia_nova);
  end if;

  return case when tg_op = 'DELETE' then old else new end;
end;
$$;

create or replace function public.reconciliar_ocorrencia(
  p_acao text,
  p_id_ocorrencia bigint default null,
  p_id_filho_tarefa bigint default null,
  p_created_at timestamptz default null,
  p_novo_tipo text default null,
  p_consequencia_tipo text default null,
  p_desconto_valor numeric default null,
  p_penalidade_descricao text default null,
  p_bonificacao_tipo text default null,
  p_bonificacao_descricao text default null,
  p_bonificacao_valor numeric default null,
  p_id_revisao bigint default null,
  p_motivo text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_pai_id bigint;
  v_id_ocorrencia bigint;
  v_id_filho_tarefa bigint;
  v_id_filho bigint;
  v_id_vigencia bigint;
  v_tem_mesada boolean;
  v_valor_mesada numeric;
  v_created_at timestamptz;
  v_tipo_anterior text;
  v_estado_anterior jsonb;
  v_estado_novo jsonb;
  v_conseq_anterior jsonb;
  v_conseq_nova jsonb;
  v_contador integer;
  v_acao text;
  v_consequencia text;
  v_revisao_status text;
  v_revisao_ft bigint;
  v_revisao_data date;
begin
  select p.id into v_pai_id
  from public.t_usuario_pai p
  where p.auth_user_id = auth.uid();

  if v_pai_id is null then raise exception 'Responsável não encontrado'; end if;

  v_acao := upper(btrim(coalesce(p_acao, '')));
  if v_acao not in ('SALVAR','DESFAZER','CUMPRIR_PENALIDADE','RESOLVER_REVISAO') then
    raise exception 'Ação de reconciliação inválida';
  end if;

  -- A função inteira executa em uma única transação PostgreSQL.
  perform set_config('app.reconciliador_ocorrencia', 'on', true);

  if p_id_ocorrencia is not null then
    select o.id, o.id_filho_tarefa, o.created_at, o.tipo,
      jsonb_build_object(
        'id',o.id,'id_filho_tarefa',o.id_filho_tarefa,'tipo',o.tipo,
        'created_at',o.created_at,'bonificacao_tipo',o.bonificacao_tipo,
        'bonificacao_descricao',o.bonificacao_descricao,
        'bonificacao_valor',o.bonificacao_valor
      )
    into v_id_ocorrencia,v_id_filho_tarefa,v_created_at,v_tipo_anterior,v_estado_anterior
    from public.t_ocorrencia o
    where o.id=p_id_ocorrencia and o.id_usuario_pai=v_pai_id
    for update;

    if v_id_ocorrencia is null then raise exception 'Ocorrência não encontrada'; end if;
  else
    v_id_filho_tarefa := p_id_filho_tarefa;
    v_created_at := p_created_at;
  end if;

  if p_id_filho_tarefa is not null
     and v_id_filho_tarefa is distinct from p_id_filho_tarefa then
    raise exception 'Não é permitido mover uma ocorrência para outra atribuição';
  end if;

  if v_id_filho_tarefa is null then raise exception 'Informe a atribuição'; end if;

  select ft.id_filho,ft.id_vigencia,
         coalesce(f.tem_mesada_opcional,false) and f.valor_mesada is not null,
         f.valor_mesada
  into v_id_filho,v_id_vigencia,v_tem_mesada,v_valor_mesada
  from public.t_filho_tarefa ft
  join public.t_filho f
    on f.id=ft.id_filho and f.id_usuario_pai=ft.id_usuario_pai
  where ft.id=v_id_filho_tarefa and ft.id_usuario_pai=v_pai_id
  for key share of ft,f;

  if v_id_filho is null then
    raise exception 'Atribuição não encontrada para este responsável';
  end if;

  if v_created_at is null then v_created_at:=now(); end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(
      v_id_filho_tarefa::text || ':' ||
      timezone('America/Sao_Paulo',v_created_at)::date::text,0
    )
  );

  select jsonb_build_object(
    'tipo',c.tipo,'desconto_valor',c.desconto_valor,
    'penalidade_descricao',c.penalidade_descricao,'status',c.status,
    'cumprida_em',c.cumprida_em,'cancelada_em',c.cancelada_em
  )
  into v_conseq_anterior
  from public.t_ocorrencia_consequencia c
  where c.id_ocorrencia=v_id_ocorrencia and c.id_usuario_pai=v_pai_id
  for update;

  if v_acao='CUMPRIR_PENALIDADE' then
    if v_id_ocorrencia is null then raise exception 'Informe a ocorrência da penalidade'; end if;

    update public.t_ocorrencia_consequencia
    set status='CUMPRIDA',cumprida_em=coalesce(cumprida_em,now()),
        cancelada_em=null,updated_at=now()
    where id_usuario_pai=v_pai_id and id_ocorrencia=v_id_ocorrencia
      and tipo='PENALIDADE' and status='PENDENTE';

    if not found then raise exception 'Penalidade pendente não encontrada'; end if;

  elsif v_acao='DESFAZER' then
    if v_id_ocorrencia is null then raise exception 'Informe a ocorrência a desfazer'; end if;

    delete from public.t_ocorrencia
    where id=v_id_ocorrencia and id_usuario_pai=v_pai_id;

    insert into public.t_ocorrencia_reconciliacao(
      id_usuario_pai,id_ocorrencia,id_filho_tarefa,acao,origem,
      id_revisao,estado_anterior,estado_novo,motivo
    ) values (
      v_pai_id,v_id_ocorrencia,v_id_filho_tarefa,'DESFAZER',
      case when p_id_revisao is null then 'RESPONSAVEL' else 'REVISAO' end,
      p_id_revisao,
      v_estado_anterior || jsonb_build_object('consequencia',v_conseq_anterior),
      null,nullif(btrim(coalesce(p_motivo,'')),'')
    );

    v_contador:=public.contar_nao_fez_filho_vigencia(v_id_filho,v_id_vigencia);

    return jsonb_build_object(
      'ok',true,'acao','DESFAZER','id_ocorrencia',v_id_ocorrencia,
      'contador_nao_fez_vigencia',v_contador
    );

  else
    if v_acao='RESOLVER_REVISAO' then
      if p_id_revisao is null or v_id_ocorrencia is null then
        raise exception 'Informe a revisão e a ocorrência';
      end if;

      select r.status,r.id_filho_tarefa,r.data_referencia
      into v_revisao_status,v_revisao_ft,v_revisao_data
      from public.t_revisao_tarefa_filho r
      join public.t_filho_tarefa ft
        on ft.id=r.id_filho_tarefa and ft.id_usuario_pai=v_pai_id
      where r.id=p_id_revisao
      for update of r;

      if v_revisao_status is null then raise exception 'Revisão não encontrada'; end if;
      if v_revisao_status<>'PENDENTE' then raise exception 'Esta revisão já foi encerrada'; end if;
      if v_revisao_ft<>v_id_filho_tarefa
         or v_revisao_data<>timezone('America/Sao_Paulo',v_created_at)::date then
        raise exception 'A revisão não pertence a esta ocorrência';
      end if;
      if v_tipo_anterior<>'NAO_FEZ' then
        raise exception 'A revisão não pertence mais a um Não fez';
      end if;
    end if;

    if upper(coalesce(p_novo_tipo,'')) not in ('FEZ','NAO_FEZ') then
      raise exception 'Tipo de ocorrência inválido';
    end if;

    if upper(p_novo_tipo)='FEZ' then
      if p_consequencia_tipo is not null or p_desconto_valor is not null
         or nullif(btrim(coalesce(p_penalidade_descricao,'')),'') is not null then
        raise exception 'Fez não pode receber consequência de Não fez';
      end if;

      if p_bonificacao_tipo is not null
         and upper(p_bonificacao_tipo) not in ('TEXTO','VALOR') then
        raise exception 'Tipo de bonificação inválido';
      end if;

      if upper(coalesce(p_bonificacao_tipo,''))='TEXTO'
         and nullif(btrim(coalesce(p_bonificacao_descricao,'')),'') is null then
        raise exception 'Informe a bonificação escrita';
      end if;

      if upper(coalesce(p_bonificacao_tipo,''))='VALOR'
         and (p_bonificacao_valor is null or p_bonificacao_valor<0) then
        raise exception 'Informe um valor de bonificação válido';
      end if;
    else
      if p_bonificacao_tipo is not null or p_bonificacao_descricao is not null
         or p_bonificacao_valor is not null then
        raise exception 'Não fez não pode receber bonificação de Fez';
      end if;

      v_consequencia:=upper(btrim(coalesce(p_consequencia_tipo,'NENHUMA')));
      if v_consequencia not in ('NENHUMA','DESCONTO','PENALIDADE') then
        raise exception 'Consequência do Não fez inválida';
      end if;

      if v_consequencia='DESCONTO' then
        if not v_tem_mesada then
          raise exception 'Desconto de mesada só pode ser aplicado a filho com mesada cadastrada';
        end if;
        if p_desconto_valor is null or p_desconto_valor<=0 then
          raise exception 'Informe um valor de desconto válido';
        end if;
        if p_desconto_valor>v_valor_mesada then
          raise exception 'O desconto desta ocorrência não pode ser maior que a mesada cadastrada';
        end if;
      elsif v_consequencia='PENALIDADE' then
        if nullif(btrim(coalesce(p_penalidade_descricao,'')),'') is null
           or char_length(btrim(p_penalidade_descricao)) not between 2 and 200 then
          raise exception 'Informe uma penalidade entre 2 e 200 caracteres';
        end if;
      end if;
    end if;

    if v_id_ocorrencia is null then
      insert into public.t_ocorrencia(
        id_usuario_pai,id_filho_tarefa,tipo,created_at,
        bonificacao_tipo,bonificacao_descricao,bonificacao_valor
      ) values (
        v_pai_id,v_id_filho_tarefa,upper(p_novo_tipo),v_created_at,
        case when upper(p_novo_tipo)='FEZ'
          then nullif(upper(coalesce(p_bonificacao_tipo,'')),'') else null end,
        case when upper(p_novo_tipo)='FEZ'
                   and upper(coalesce(p_bonificacao_tipo,''))='TEXTO'
          then nullif(btrim(coalesce(p_bonificacao_descricao,'')),'') else null end,
        case when upper(p_novo_tipo)='FEZ'
                   and upper(coalesce(p_bonificacao_tipo,''))='VALOR'
          then p_bonificacao_valor else null end
      )
      returning id,created_at into v_id_ocorrencia,v_created_at;
      v_estado_anterior:=null;
    else
      update public.t_ocorrencia
      set tipo=upper(p_novo_tipo),
          created_at=coalesce(p_created_at,created_at),
          bonificacao_tipo=case when upper(p_novo_tipo)='FEZ'
            then nullif(upper(coalesce(p_bonificacao_tipo,'')),'') else null end,
          bonificacao_descricao=case when upper(p_novo_tipo)='FEZ'
                 and upper(coalesce(p_bonificacao_tipo,''))='TEXTO'
            then nullif(btrim(coalesce(p_bonificacao_descricao,'')),'') else null end,
          bonificacao_valor=case when upper(p_novo_tipo)='FEZ'
                 and upper(coalesce(p_bonificacao_tipo,''))='VALOR'
            then p_bonificacao_valor else null end
      where id=v_id_ocorrencia and id_usuario_pai=v_pai_id
      returning created_at into v_created_at;
    end if;

    if upper(p_novo_tipo)='FEZ' then
      update public.t_ocorrencia_consequencia
      set status=case
            when tipo='DESCONTO' and status='APLICADO' then 'ESTORNADO'
            when tipo='PENALIDADE' and status='PENDENTE' then 'CANCELADA'
            else status end,
          cancelada_em=case when tipo='PENALIDADE' and status='PENDENTE'
            then now() else cancelada_em end,
          updated_at=now()
      where id_usuario_pai=v_pai_id and id_ocorrencia=v_id_ocorrencia;
    else
      if v_consequencia='NENHUMA' then
        delete from public.t_ocorrencia_consequencia
        where id_usuario_pai=v_pai_id and id_ocorrencia=v_id_ocorrencia;
      elsif v_consequencia='DESCONTO' then
        insert into public.t_ocorrencia_consequencia(
          id_usuario_pai,id_ocorrencia,tipo,desconto_valor,
          penalidade_descricao,status,cumprida_em,cancelada_em
        ) values (
          v_pai_id,v_id_ocorrencia,'DESCONTO',p_desconto_valor,
          null,'APLICADO',null,null
        )
        on conflict(id_ocorrencia) do update
        set tipo='DESCONTO',desconto_valor=excluded.desconto_valor,
            penalidade_descricao=null,status='APLICADO',
            cumprida_em=null,cancelada_em=null,updated_at=now();
      else
        insert into public.t_ocorrencia_consequencia(
          id_usuario_pai,id_ocorrencia,tipo,desconto_valor,
          penalidade_descricao,status,cumprida_em,cancelada_em
        ) values (
          v_pai_id,v_id_ocorrencia,'PENALIDADE',null,
          btrim(p_penalidade_descricao),'PENDENTE',null,null
        )
        on conflict(id_ocorrencia) do update
        set tipo='PENALIDADE',desconto_valor=null,
            penalidade_descricao=excluded.penalidade_descricao,
            status='PENDENTE',cumprida_em=null,cancelada_em=null,updated_at=now();
      end if;
    end if;

    if v_acao='RESOLVER_REVISAO' then
      update public.t_revisao_tarefa_filho
      set status=case when upper(p_novo_tipo)='FEZ'
          then 'ALTERADO_PARA_FEZ' else 'MANTEVE_NAO_FEZ' end,
          resolvido_em=now()
      where id=p_id_revisao and status='PENDENTE';
    end if;
  end if;

  select jsonb_build_object(
    'id',o.id,'id_filho_tarefa',o.id_filho_tarefa,'tipo',o.tipo,
    'created_at',o.created_at,'bonificacao_tipo',o.bonificacao_tipo,
    'bonificacao_descricao',o.bonificacao_descricao,
    'bonificacao_valor',o.bonificacao_valor
  ) into v_estado_novo
  from public.t_ocorrencia o where o.id=v_id_ocorrencia;

  select jsonb_build_object(
    'tipo',c.tipo,'desconto_valor',c.desconto_valor,
    'penalidade_descricao',c.penalidade_descricao,'status',c.status,
    'cumprida_em',c.cumprida_em,'cancelada_em',c.cancelada_em
  ) into v_conseq_nova
  from public.t_ocorrencia_consequencia c
  where c.id_ocorrencia=v_id_ocorrencia and c.id_usuario_pai=v_pai_id;

  insert into public.t_ocorrencia_reconciliacao(
    id_usuario_pai,id_ocorrencia,id_filho_tarefa,acao,origem,
    id_revisao,estado_anterior,estado_novo,motivo
  ) values (
    v_pai_id,v_id_ocorrencia,v_id_filho_tarefa,
    case when v_acao='CUMPRIR_PENALIDADE' then 'CUMPRIR_PENALIDADE'
         when v_acao='RESOLVER_REVISAO' then 'RESOLVER_REVISAO'
         when v_estado_anterior is null then 'CRIAR' else 'ALTERAR' end,
    case when v_acao='RESOLVER_REVISAO' then 'REVISAO' else 'RESPONSAVEL' end,
    p_id_revisao,
    case when v_estado_anterior is null then null
      else v_estado_anterior || jsonb_build_object('consequencia',v_conseq_anterior) end,
    v_estado_novo || jsonb_build_object('consequencia',v_conseq_nova),
    nullif(btrim(coalesce(p_motivo,'')),'')
