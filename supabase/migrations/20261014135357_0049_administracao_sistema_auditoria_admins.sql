CREATE TABLE IF NOT EXISTS public.t_app_config (
  id smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  mensagem_global_ativa boolean NOT NULL DEFAULT false,
  mensagem_global text NULL,
  manutencao_ativa boolean NOT NULL DEFAULT false,
  manutencao_mensagem text NULL,
  android_min_version_name text NULL,
  android_min_version_code integer NULL CHECK (android_min_version_code IS NULL OR android_min_version_code > 0),
  ios_min_version_name text NULL,
  ios_min_version_code integer NULL CHECK (ios_min_version_code IS NULL OR ios_min_version_code > 0),
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by_admin_id bigint NULL REFERENCES public.t_admin(id) ON DELETE SET NULL
);

INSERT INTO public.t_app_config (id)
VALUES (1)
ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.t_app_feature_flag (
  chave text PRIMARY KEY,
  nome text NOT NULL,
  descricao text NULL,
  ativo boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by_admin_id bigint NULL REFERENCES public.t_admin(id) ON DELETE SET NULL,
  CONSTRAINT t_app_feature_flag_chave_check
    CHECK (chave ~ '^[a-z0-9][a-z0-9_.-]{1,63}$')
);

CREATE TABLE IF NOT EXISTS public.t_admin_auditoria (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_admin bigint NOT NULL REFERENCES public.t_admin(id) ON DELETE RESTRICT,
  acao text NOT NULL,
  entidade text NOT NULL,
  entidade_id text NULL,
  detalhes jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_t_admin_auditoria_created_at
  ON public.t_admin_auditoria (created_at DESC);

CREATE INDEX IF NOT EXISTS idx_t_admin_auditoria_admin_created_at
  ON public.t_admin_auditoria (id_admin, created_at DESC);

ALTER TABLE public.t_app_config ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.t_app_feature_flag ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.t_admin_auditoria ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.t_app_config FROM anon, authenticated;
REVOKE ALL ON public.t_app_feature_flag FROM anon, authenticated;
REVOKE ALL ON public.t_admin_auditoria FROM anon, authenticated;

CREATE OR REPLACE FUNCTION public.current_admin_id()
RETURNS bigint
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
  SELECT a.id
  FROM public.t_admin a
  JOIN public.t_usuario_pai p ON p.id = a.id_usuario_pai
  WHERE a.ativo = true
    AND p.auth_user_id = auth.uid()
  LIMIT 1
$function$;

