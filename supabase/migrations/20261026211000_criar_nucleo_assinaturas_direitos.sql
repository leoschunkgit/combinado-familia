create or replace function billing.touch_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = billing, pg_temp
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

revoke all on function billing.touch_updated_at()
  from public, anon, authenticated;

do $$
declare
  t text;
begin
  foreach t in array array[
    'plano',
    'recurso',
    'plano_recurso',
    'oferta',
    'assinatura',
    'assinatura_provedor',
    'direito_override'
  ]
  loop
    execute format(
      'drop trigger if exists trg_%I_updated_at on billing.%I',
      t,
      t
    );
    execute format(
      'create trigger trg_%I_updated_at before update on billing.%I for each row execute function billing.touch_updated_at()',
      t,
      t
    );
  end loop;
end $$;

create or replace function billing.validar_valor_recurso()
returns trigger
language plpgsql
security invoker
set search_path = billing, pg_temp
as $$
declare
  v_tipo text;
  v_json_tipo text;
begin
  select tipo
    into v_tipo
    from billing.recurso
   where id = new.id_recurso;

  if v_tipo is null then
    raise exception 'Recurso inexistente.';
  end if;

  v_json_tipo := jsonb_typeof(new.valor);

  if v_tipo = 'BOOLEANO' and v_json_tipo <> 'boolean' then
    raise exception 'Recurso BOOLEANO exige valor boolean.';
  elsif v_tipo = 'LIMITE_INTEIRO'
        and (
          v_json_tipo <> 'number'
          or (new.valor #>> '{}') !~ '^-?[0-9]+$'
        ) then
    raise exception 'Recurso LIMITE_INTEIRO exige número inteiro.';
  elsif v_tipo = 'NUMERO' and v_json_tipo <> 'number' then
    raise exception 'Recurso NUMERO exige valor numérico.';
  elsif v_tipo = 'TEXTO' and v_json_tipo <> 'string' then
    raise exception 'Recurso TEXTO exige string.';
  elsif v_tipo = 'JSON' and v_json_tipo not in ('object','array') then
    raise exception 'Recurso JSON exige objeto ou array.';
  end if;

  return new;
end;
$$;

revoke all on function billing.validar_valor_recurso()
  from public, anon, authenticated;

drop trigger if exists trg_plano_recurso_validar_valor
