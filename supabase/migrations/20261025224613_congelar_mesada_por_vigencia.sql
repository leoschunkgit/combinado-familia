
create table if not exists public.t_filho_vigencia_mesada (
  id bigint generated by default as identity primary key,
  id_usuario_pai bigint not null,
  id_filho bigint not null,
  id_vigencia bigint not null,
  tem_mesada boolean not null default false,
  valor_mesada numeric null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint t_filho_vigencia_mesada_coerente_chk
    check (
      (tem_mesada = false and valor_mesada is null)
      or
      (tem_mesada = true and valor_mesada is not null and valor_mesada > 0)
    ),

  constraint t_filho_vigencia_mesada_pai_filho_fk
    foreign key (id_usuario_pai, id_filho)
    references public.t_filho(id_usuario_pai, id)
    on delete cascade,

  constraint t_filho_vigencia_mesada_pai_vigencia_fk
    foreign key (id_usuario_pai, id_vigencia)
    references public.t_vigencia(id_usuario_pai, id)
    on delete cascade,

  constraint t_filho_vigencia_mesada_pai_filho_vigencia_uq
    unique (id_usuario_pai, id_filho, id_vigencia)
);

alter table public.t_filho_vigencia_mesada enable row level security;

drop policy if exists t_filho_vigencia_mesada_select_own
  on public.t_filho_vigencia_mesada;

create policy t_filho_vigencia_mesada_select_own
on public.t_filho_vigencia_mesada
for select
to authenticated
using (id_usuario_pai = public.current_pai_id());

revoke all on table public.t_filho_vigencia_mesada from public, anon, authenticated;
grant select on table public.t_filho_vigencia_mesada to authenticated;


create or replace function public.sincronizar_mesada_vigencia_atribuicao_interno()
returns trigger
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_tem_mesada boolean;
  v_valor_mesada numeric;
begin
  if tg_op in ('UPDATE', 'DELETE') then
    if not exists (
      select 1
      from public.t_filho_tarefa ft
      where ft.id_usuario_pai = old.id_usuario_pai
        and ft.id_filho = old.id_filho
        and ft.id_vigencia = old.id_vigencia
    ) then
      delete from public.t_filho_vigencia_mesada m
      where m.id_usuario_pai = old.id_usuario_pai
        and m.id_filho = old.id_filho
        and m.id_vigencia = old.id_vigencia;
    end if;
  end if;

  if tg_op in ('INSERT', 'UPDATE') then
    select
      coalesce(f.tem_mesada_opcional, false) and f.valor_mesada is not null,
      case
        when coalesce(f.tem_mesada_opcional, false) and f.valor_mesada is not null
          then f.valor_mesada
        else null
      end
    into v_tem_mesada, v_valor_mesada
    from public.t_filho f
    where f.id_usuario_pai = new.id_usuario_pai
      and f.id = new.id_filho;

    insert into public.t_filho_vigencia_mesada (
      id_usuario_pai,
      id_filho,
      id_vigencia,
      tem_mesada,
      valor_mesada
    )
    values (
      new.id_usuario_pai,
      new.id_filho,
      new.id_vigencia,
      coalesce(v_tem_mesada, false),
      v_valor_mesada
    )
    on conflict (id_usuario_pai, id_filho, id_vigencia)
    do update
      set tem_mesada = excluded.tem_mesada,
          valor_mesada = excluded.valor_mesada,
          updated_at = now()
    where exists (
      select 1
      from public.t_vigencia v
      where v.id = excluded.id_vigencia
        and v.id_usuario_pai = excluded.id_usuario_pai
        and v.data_fim >= now()
    );
  end if;

  return coalesce(new, old);
end;
$function$;

revoke all
on function public.sincronizar_mesada_vigencia_atribuicao_interno()
from public, anon, authenticated, service_role;

drop trigger if exists sincronizar_mesada_vigencia_atribuicao_after_change
  on public.t_filho_tarefa;

create trigger sincronizar_mesada_vigencia_atribuicao_after_change
after insert or delete or update of id_usuario_pai, id_filho, id_vigencia
on public.t_filho_tarefa
for each row
execute function public.sincronizar_mesada_vigencia_atribuicao_interno();


create or replace function public.sincronizar_mesada_vigencia_filho_interno()
returns trigger
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_tem_mesada boolean;
  v_valor_mesada numeric;
begin
  v_tem_mesada :=
    coalesce(new.tem_mesada_opcional, false)
    and new.valor_mesada is not null;

  v_valor_mesada :=
    case when v_tem_mesada then new.valor_mesada else null end;

  update public.t_filho_vigencia_mesada m
  set tem_mesada = v_tem_mesada,
      valor_mesada = v_valor_mesada,
      updated_at = now()
  from public.t_vigencia v
  where m.id_usuario_pai = new.id_usuario_pai
    and m.id_filho = new.id
    and v.id = m.id_vigencia
    and v.id_usuario_pai = m.id_usuario_pai
    and v.data_fim >= now();

  return new;
end;
$function$;

revoke all
on function public.sincronizar_mesada_vigencia_filho_interno()
from public, anon, authenticated, service_role;

drop trigger if exists sincronizar_mesada_vigencia_filho_after_change
  on public.t_filho;

create trigger sincronizar_mesada_vigencia_filho_after_change
after update of tem_mesada, tem_mesada_opcional, valor_mesada
on public.t_filho
for each row
when (
  old.tem_mesada is distinct from new.tem_mesada
  or old.tem_mesada_opcional is distinct from new.tem_mesada_opcional
  or old.valor_mesada is distinct from new.valor_mesada
)
execute function public.sincronizar_mesada_vigencia_filho_interno();


with pares as (
  select distinct
    ft.id_usuario_pai,
    ft.id_filho,
    ft.id_vigencia
  from public.t_filho_tarefa ft
),
descontos as (
  select
    ft.id_usuario_pai,
    ft.id_filho,
    ft.id_vigencia,
    coalesce(sum(c.desconto_valor), 0)::numeric as total_descontos
  from public.t_filho_tarefa ft
  join public.t_ocorrencia o
    on o.id_filho_tarefa = ft.id
   and o.id_usuario_pai = ft.id_usuario_pai
   and o.tipo = 'NAO_FEZ'
  join public.t_ocorrencia_consequencia c
    on c.id_ocorrencia = o.id
   and c.id_usuario_pai = o.id_usuario_pai
   and c.tipo = 'DESCONTO'
   and c.status = 'APLICADO'
  group by ft.id_usuario_pai, ft.id_filho, ft.id_vigencia
)
insert into public.t_filho_vigencia_mesada (
  id_usuario_pai,
  id_filho,
  id_vigencia,
  tem_mesada,
  valor_mesada
)
select
  p.id_usuario_pai,
  p.id_filho,
  p.id_vigencia,
  (
    (coalesce(f.tem_mesada_opcional, false) and f.valor_mesada is not null)
    or coalesce(d.total_descontos, 0) > 0
  ) as tem_mesada,
  case
    when (coalesce(f.tem_mesada_opcional, false) and f.valor_mesada is not null)
      or coalesce(d.total_descontos, 0) > 0
    then greatest(
      coalesce(f.valor_mesada, 0),
      coalesce(d.total_descontos, 0)
    )
    else null
  end as valor_mesada
from pares p
join public.t_filho f
  on f.id = p.id_filho
 and f.id_usuario_pai = p.id_usuario_pai
left join descontos d
  on d.id_usuario_pai = p.id_usuario_pai
 and d.id_filho = p.id_filho
 and d.id_vigencia = p.id_vigencia
on conflict (id_usuario_pai, id_filho, id_vigencia)
do nothing;

create index if not exists idx_t_filho_vigencia_mesada_pai_vigencia
  on public.t_filho_vigencia_mesada (id_usuario_pai, id_vigencia);

create index if not exists idx_t_filho_vigencia_mesada_pai_filho
  on public.t_filho_vigencia_mesada (id_usuario_pai, id_filho);
