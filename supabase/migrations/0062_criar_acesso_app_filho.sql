create table if not exists public.t_filho_acesso_app_chave (
  id bigint generated by default as identity primary key,
  id_usuario_pai bigint not null references public.t_usuario_pai(id) on delete cascade,
  id_filho bigint not null references public.t_filho(id) on delete cascade,
  chave_hash text not null,
  expira_em timestamptz not null,
  usado_em timestamptz null,
  tentativas integer not null default 0,
  max_tentativas integer not null default 5,
  ativo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint t_filho_acesso_app_chave_tentativas_chk check (tentativas >= 0),
  constraint t_filho_acesso_app_chave_max_tentativas_chk check (max_tentativas between 1 and 20)
);

create index if not exists idx_t_filho_acesso_app_chave_filho
  on public.t_filho_acesso_app_chave (id_usuario_pai, id_filho);

create index if not exists idx_t_filho_acesso_app_chave_ativa_expira
  on public.t_filho_acesso_app_chave (ativo, expira_em);

create table if not exists public.t_filho_acesso_app (
  id bigint generated by default as identity primary key,
  id_usuario_pai bigint not null references public.t_usuario_pai(id) on delete cascade,
  id_filho bigint not null references public.t_filho(id) on delete cascade,
  token_hash text not null unique,
  dispositivo_id uuid not null default gen_random_uuid(),
  dispositivo_nome text null,
  ativo boolean not null default true,
  ultimo_acesso_em timestamptz null,
  revogado_em timestamptz null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_t_filho_acesso_app_filho
  on public.t_filho_acesso_app (id_usuario_pai, id_filho);

create index if not exists idx_t_filho_acesso_app_ativo
  on public.t_filho_acesso_app (ativo)
  where ativo = true;

alter table public.t_filho_acesso_app_chave enable row level security;
alter table public.t_filho_acesso_app enable row level security;

drop policy if exists t_filho_acesso_app_chave_parent_select on public.t_filho_acesso_app_chave;
create policy t_filho_acesso_app_chave_parent_select
on public.t_filho_acesso_app_chave
for select
to authenticated
using (id_usuario_pai = public.current_pai_id());

drop policy if exists t_filho_acesso_app_parent_select on public.t_filho_acesso_app;
create policy t_filho_acesso_app_parent_select
on public.t_filho_acesso_app
for select
to authenticated
using (id_usuario_pai = public.current_pai_id());

revoke all on public.t_filho_acesso_app_chave from anon;
revoke all on public.t_filho_acesso_app from anon;

grant select on public.t_filho_acesso_app_chave to authenticated;
grant select on public.t_filho_acesso_app to authenticated;
