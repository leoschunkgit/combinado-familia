CREATE TABLE IF NOT EXISTS public.t_app_telemetria (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario_pai bigint NOT NULL UNIQUE
    REFERENCES public.t_usuario_pai(id)
    ON DELETE CASCADE,
  plataforma text NOT NULL,
  version_name text NULL,
  version_code integer NULL,
  first_seen_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT t_app_telemetria_plataforma_check
    CHECK (plataforma IN ('web', 'android', 'ios'))
);

ALTER TABLE public.t_app_telemetria ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.t_app_telemetria FROM anon;
REVOKE ALL ON public.t_app_telemetria FROM authenticated;

CREATE OR REPLACE FUNCTION public.registrar_telemetria_app(
  p_plataforma text,
  p_version_name text DEFAULT NULL,
  p_version_code integer DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_id_usuario_pai bigint;
  v_plataforma text;
BEGIN
  v_id_usuario_pai := public.current_pai_id();
  IF v_id_usuario_pai IS NULL THEN
    RAISE EXCEPTION 'Usuário responsável não encontrado'
      USING ERRCODE = '42501';
  END IF;

  v_plataforma := lower(trim(coalesce(p_plataforma, '')));
  IF v_plataforma NOT IN ('web', 'android', 'ios') THEN
    RAISE EXCEPTION 'Plataforma inválida';
  END IF;

  INSERT INTO public.t_app_telemetria (
    id_usuario_pai,
    plataforma,
    version_name,
    version_code,
    first_seen_at,
    last_seen_at,
    updated_at
  )
  VALUES (
    v_id_usuario_pai,
    v_plataforma,
    nullif(trim(coalesce(p_version_name, '')), ''),
    p_version_code,
    now(),
    now(),
    now()
  )
  ON CONFLICT (id_usuario_pai)
  DO UPDATE SET
    plataforma = EXCLUDED.plataforma,
    version_name = EXCLUDED.version_name,
    version_code = EXCLUDED.version_code,
    last_seen_at = now(),
    updated_at = now();
END;
$function$;

REVOKE ALL ON FUNCTION public.registrar_telemetria_app(text, text, integer) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.registrar_telemetria_app(text, text, integer) TO authenticated;

CREATE OR REPLACE FUNCTION public.admin_operacao()
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_result jsonb;
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'Acesso administrativo não autorizado'
      USING ERRCODE = '42501';
  END IF;

  SELECT jsonb_build_object(
    'atividade', jsonb_build_object(
      'usuarios_monitorados', (SELECT count(*) FROM public.t_app_telemetria),
      'usuarios_sem_telemetria', (
        SELECT greatest(
          (SELECT count(*) FROM public.t_usuario_pai)
          - (SELECT count(*) FROM public.t_app_telemetria),
          0
        )
      ),
      'ativos_hoje', (
        SELECT count(*)
        FROM public.t_app_telemetria
        WHERE (last_seen_at AT TIME ZONE 'America/Sao_Paulo')::date =
              (now() AT TIME ZONE 'America/Sao_Paulo')::date
      ),
      'ativos_7d', (
        SELECT count(*)
        FROM public.t_app_telemetria
        WHERE last_seen_at >= now() - interval '7 days'
      ),
      'ativos_30d', (
        SELECT count(*)
        FROM public.t_app_telemetria
        WHERE last_seen_at >= now() - interval '30 days'
      ),
      'ultimo_acesso', (
        SELECT max(last_seen_at)
        FROM public.t_app_telemetria
      )
    ),
    'plataformas', jsonb_build_object(
      'web', (
        SELECT count(*)
        FROM public.t_app_telemetria
        WHERE plataforma = 'web'
      ),
      'android', (
        SELECT count(*)
        FROM public.t_app_telemetria
        WHERE plataforma = 'android'
      ),
      'ios', (
        SELECT count(*)
        FROM public.t_app_telemetria
        WHERE plataforma = 'ios'
      )
    ),
    'versoes', COALESCE((
      SELECT jsonb_agg(
        jsonb_build_object(
          'plataforma', x.plataforma,
          'version_name', x.version_name,
          'version_code', x.version_code,
          'usuarios', x.usuarios
        )
        ORDER BY x.usuarios DESC, x.plataforma, x.version_name DESC NULLS LAST
      )
      FROM (
        SELECT
          plataforma,
          version_name,
          version_code,
          count(*) AS usuarios
        FROM public.t_app_telemetria
        GROUP BY plataforma, version_name, version_code
      ) x
    ), '[]'::jsonb),
    'saude', jsonb_build_object(
      'banco_agora', now(),
      'cron_push_configurado', EXISTS (
        SELECT 1
        FROM public.app_cron_config
        WHERE chave = 'push_cron_secret'
          AND nullif(trim(valor), '') IS NOT NULL
      ),
      'ultimo_push_envio', (
        SELECT max(created_at)
        FROM public.t_push_envio
      ),
      'ultima_referencia_push', (
        SELECT max(data_referencia)
        FROM public.t_push_envio
      )
    )
  )
  INTO v_result;

  RETURN v_result;
END;
$function$;

REVOKE ALL ON FUNCTION public.admin_operacao() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.admin_operacao() TO authenticated;
