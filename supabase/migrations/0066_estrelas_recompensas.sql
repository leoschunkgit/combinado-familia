-- Sistema de estrelas e recompensas.
-- Regras:
-- 1 FEZ atual = 1 estrela.
-- NAO_FEZ nao gera nem remove estrela por si so.
-- FEZ -> NAO_FEZ ou exclusao de FEZ gera estorno.
-- NAO_FEZ -> FEZ gera uma nova estrela.
-- Alterar apenas bonificacao de um FEZ nao altera estrelas.
-- Resgates descontam do saldo; cancelamentos devolvem.
-- Mesada, desconto, limite e penalidade permanecem independentes.

create table if not exists public.t_estrela_movimento (
  id bigint generated by default as identity primary key,
  id_usuario_pai bigint not null references public.t_usuario_pai(id) on delete cascade,
  id_filho bigint not null references public.t_filho(id) on delete cascade,
  id_vigencia bigint null references public.t_vigencia(id) on delete set null,
  id_tarefa bigint null references public.t_tarefa(id) on delete set null,
  id_ocorrencia bigint null,
  id_resgate bigint null,
  tipo text not null,
  quantidade integer not null,
  descricao text null,
  data_referencia date null,
  created_at timestamptz not null default now(),
  constraint t_estrela_movimento_tipo_chk
    check (tipo in ('FEZ', 'ESTORNO_FEZ', 'RESGATE', 'CANCELAMENTO_RESGATE')),
  constraint t_estrela_movimento_quantidade_chk
    check (
      (tipo in ('FEZ', 'CANCELAMENTO_RESGATE') and quantidade > 0)
      or
      (tipo in ('ESTORNO_FEZ', 'RESGATE') and quantidade < 0)
    )
);

create index if not exists t_estrela_movimento_filho_idx
  on public.t_estrela_movimento(id_usuario_pai, id_filho, created_at desc);

create index if not exists t_estrela_movimento_ocorrencia_idx
  on public.t_estrela_movimento(id_ocorrencia)
  where id_ocorrencia is not null;

create index if not exists t_estrela_movimento_vigencia_idx
  on public.t_estrela_movimento(id_usuario_pai, id_filho, id_vigencia)
  where id_vigencia is not null;

create table if not exists public.t_recompensa_estrela (
  id bigint generated by default as identity primary key,
  id_usuario_pai bigint not null references public.t_usuario_pai(id) on delete cascade,
  id_filho bigint not null references public.t_filho(id) on delete cascade,
  nome text not null,
  descricao text null,
  estrelas_necessarias integer not null,
  ativo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint t_recompensa_estrela_nome_chk
    check (char_length(btrim(nome)) between 2 and 100),
  constraint t_recompensa_estrela_descricao_chk
    check (descricao is null or char_length(descricao) <= 300),
  constraint t_recompensa_estrela_estrelas_chk
    check (estrelas_necessarias between 1 and 100000)
);

create index if not exists t_recompensa_estrela_filho_idx
  on public.t_recompensa_estrela(id_usuario_pai, id_filho, ativo, estrelas_necessarias);

create table if not exists public.t_recompensa_resgate (
  id bigint generated by default as identity primary key,
  id_usuario_pai bigint not null references public.t_usuario_pai(id) on delete cascade,
  id_filho bigint not null references public.t_filho(id) on delete cascade,
  id_recompensa bigint not null references public.t_recompensa_estrela(id),
  recompensa_nome text not null,
  estrelas_utilizadas integer not null,
  status text not null default 'PENDENTE',
  created_at timestamptz not null default now(),
  entregue_em timestamptz null,
  cancelado_em timestamptz null,
  updated_at timestamptz not null default now(),
  constraint t_recompensa_resgate_estrelas_chk
    check (estrelas_utilizadas between 1 and 100000),
  constraint t_recompensa_resgate_status_chk
    check (status in ('PENDENTE', 'ENTREGUE', 'CANCELADO'))
);

create index if not exists t_recompensa_resgate_filho_idx
  on public.t_recompensa_resgate(id_usuario_pai, id_filho, created_at desc);

