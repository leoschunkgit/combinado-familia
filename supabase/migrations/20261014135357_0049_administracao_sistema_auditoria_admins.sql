CREATE OR REPLACE FUNCTION public.admin_feature_salvar(
  p_chave text,
  p_nome text,
  p_descricao text,
  p_ativo boolean
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_admin_id bigint;
  v_chave text;
  v_existia boolean;
  v_result jsonb;
BEGIN
  v_admin_id := public.current_admin_id();
  IF v_admin_id IS NULL THEN
    RAISE EXCEPTION 'Acesso administrativo não autorizado'
      USING ERRCODE = '42501';
  END IF;

  v_chave := lower(trim(coalesce(p_chave, '')));

  IF v_chave !~ '^[a-z0-9][a-z0-9_.-]{1,63}$' THEN
    RAISE EXCEPTION 'Chave inválida. Use letras minúsculas, números, ponto, hífen ou sublinhado';
  END IF;

  IF nullif(trim(coalesce(p_nome, '')), '') IS NULL THEN
    RAISE EXCEPTION 'Informe o nome da funcionalidade';
  END IF;

  SELECT EXISTS (
    SELECT 1 FROM public.t_app_feature_flag WHERE chave = v_chave
  )
  INTO v_existia;

  INSERT INTO public.t_app_feature_flag (
    chave,
    nome,
    descricao,
    ativo,
    updated_by_admin_id
  )
  VALUES (
    v_chave,
    trim(p_nome),
    nullif(trim(coalesce(p_descricao, '')), ''),
    coalesce(p_ativo, false),
    v_admin_id
  )
  ON CONFLICT (chave)
  DO UPDATE SET
    nome = EXCLUDED.nome,
    descricao = EXCLUDED.descricao,
    ativo = EXCLUDED.ativo,
    updated_at = now(),
    updated_by_admin_id = v_admin_id;

  SELECT jsonb_build_object(
    'chave', f.chave,
    'nome', f.nome,
    'descricao', f.descricao,
    'ativo', f.ativo,
    'created_at', f.created_at,
    'updated_at', f.updated_at
  )
  INTO v_result
  FROM public.t_app_feature_flag f
  WHERE f.chave = v_chave;

  PERFORM public.admin_auditar(
    CASE WHEN v_existia THEN 'FEATURE_FLAG_ALTERADA' ELSE 'FEATURE_FLAG_CRIADA' END,
    'feature_flag',
    v_chave,
    v_result
  );

  RETURN v_result;
END;
$function$;

REVOKE ALL ON FUNCTION public.admin_feature_salvar(text, text, text, boolean) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.admin_feature_salvar(text, text, text, boolean) TO authenticated;

