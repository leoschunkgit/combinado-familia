create or replace function public.resgatar_recompensa_estrelas(p_id_recompensa bigint)
returns bigint
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_pai_id bigint;
  v_filho_id bigint;
  v_nome text;
  v_custo integer;
  v_saldo integer;
  v_resgate_id bigint;
begin
  select p.id into v_pai_id
  from public.t_usuario_pai p
  where p.auth_user_id = auth.uid();

  if v_pai_id is null then
    raise exception 'Responsável não encontrado';
  end if;

  select r.id_filho, r.nome, r.estrelas_necessarias
    into v_filho_id, v_nome, v_custo
  from public.t_recompensa_estrela r
  where r.id = p_id_recompensa
    and r.id_usuario_pai = v_pai_id
    and r.ativo = true;

  if v_filho_id is null then
    raise exception 'Recompensa não encontrada ou inativa';
  end if;

  perform 1
  from public.t_filho f
  where f.id = v_filho_id
    and f.id_usuario_pai = v_pai_id
  for update;

  v_saldo := public.estrelas_saldo_filho_interno(v_pai_id, v_filho_id);

  if v_saldo < v_custo then
    raise exception 'Saldo de estrelas insuficiente';
  end if;

  insert into public.t_recompensa_resgate (
    id_usuario_pai,
    id_filho,
    id_recompensa,
    recompensa_nome,
    estrelas_utilizadas,
    status
  )
  values (
    v_pai_id,
    v_filho_id,
    p_id_recompensa,
    v_nome,
    v_custo,
    'PENDENTE'
  )
  returning id into v_resgate_id;

  insert into public.t_estrela_movimento (
    id_usuario_pai,
    id_filho,
    id_resgate,
    tipo,
    quantidade,
    descricao
  )
  values (
    v_pai_id,
    v_filho_id,
    v_resgate_id,
    'RESGATE',
    -v_custo,
    v_nome
  );

  return v_resgate_id;
end;
$function$;

create or replace function public.alterar_status_resgate_estrelas(
  p_id_resgate bigint,
  p_status text
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_pai_id bigint;
  v_filho_id bigint;
  v_status_atual text;
  v_custo integer;
  v_nome text;
begin
  select p.id into v_pai_id
  from public.t_usuario_pai p
  where p.auth_user_id = auth.uid();

  if v_pai_id is null then
    raise exception 'Responsável não encontrado';
  end if;

  if p_status not in ('ENTREGUE', 'CANCELADO') then
    raise exception 'Status de resgate inválido';
  end if;

  select
    rr.id_filho,
    rr.status,
    rr.estrelas_utilizadas,
    rr.recompensa_nome
  into
    v_filho_id,
    v_status_atual,
    v_custo,
    v_nome
  from public.t_recompensa_resgate rr
  where rr.id = p_id_resgate
    and rr.id_usuario_pai = v_pai_id
  for update;

  if v_filho_id is null then
    raise exception 'Resgate não encontrado';
  end if;

  perform 1
  from public.t_filho f
  where f.id = v_filho_id
    and f.id_usuario_pai = v_pai_id
  for update;

  if p_status = 'ENTREGUE' then
    if v_status_atual = 'CANCELADO' then
      raise exception 'Resgate cancelado não pode ser marcado como entregue';
    end if;

    if v_status_atual = 'ENTREGUE' then
      return true;
    end if;

    update public.t_recompensa_resgate
    set status = 'ENTREGUE',
        entregue_em = coalesce(entregue_em, now()),
        updated_at = now()
    where id = p_id_resgate
      and id_usuario_pai = v_pai_id;

    return true;
  end if;

  if v_status_atual = 'CANCELADO' then
    return true;
  end if;

  update public.t_recompensa_resgate
  set status = 'CANCELADO',
      cancelado_em = coalesce(cancelado_em, now()),
      updated_at = now()
  where id = p_id_resgate
    and id_usuario_pai = v_pai_id;

  insert into public.t_estrela_movimento (
    id_usuario_pai,
    id_filho,
    id_resgate,
    tipo,
    quantidade,
    descricao
  )
  values (
    v_pai_id,
    v_filho_id,
    p_id_resgate,
    'CANCELAMENTO_RESGATE',
    v_custo,
    v_nome
  );

  return true;
end;
$function$;

