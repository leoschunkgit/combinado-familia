-- 0072 - Pedido unico de revisao de "Nao fez" pelo filho.
-- A decisao oficial continua em t_ocorrencia. A revisao apenas registra a contestacao
-- e fecha definitivamente em MANTEVE_NAO_FEZ ou ALTERADO_PARA_FEZ.

create table if not exists public.t_revisao_tarefa_filho (
  id bigint generated by default as identity primary key,
  id_filho_tarefa bigint not null references public.t_filho_tarefa(id) on delete cascade,
  data_referencia date not null,
  observacao text null,
  status text not null default 'PENDENTE',
  created_at timestamptz not null default now(),
  resolvido_em timestamptz null,
  constraint t_revisao_tarefa_filho_observacao_chk check (
    observacao is null or (
      char_length(btrim(observacao)) between 1 and 120
      and observacao = btrim(observacao)
    )
  ),
  constraint t_revisao_tarefa_filho_status_chk
    check (status in ('PENDENTE', 'MANTEVE_NAO_FEZ', 'ALTERADO_PARA_FEZ')),
  constraint t_revisao_tarefa_filho_resolucao_chk check (
    (status = 'PENDENTE' and resolvido_em is null)
    or (status <> 'PENDENTE' and resolvido_em is not null)
  ),
  constraint t_revisao_tarefa_filho_unica_tarefa_dia
    unique (id_filho_tarefa, data_referencia)
);

create index if not exists idx_revisao_tarefa_filho_data
  on public.t_revisao_tarefa_filho (data_referencia, id_filho_tarefa);

alter table public.t_revisao_tarefa_filho enable row level security;

revoke all privileges on table public.t_revisao_tarefa_filho
from public, anon, authenticated, service_role;

revoke all privileges on sequence public.t_revisao_tarefa_filho_id_seq
from public, anon, authenticated, service_role;

grant select on table public.t_revisao_tarefa_filho to authenticated;

drop policy if exists revisao_tarefa_filho_select_responsavel
  on public.t_revisao_tarefa_filho;

create policy revisao_tarefa_filho_select_responsavel
on public.t_revisao_tarefa_filho
for select
to authenticated
using (
  exists (
    select 1
    from public.t_filho_tarefa ft
    where ft.id = t_revisao_tarefa_filho.id_filho_tarefa
      and ft.id_usuario_pai = public.current_pai_id()
  )
);

comment on table public.t_revisao_tarefa_filho is
  'Pedido unico de revisao do filho para um NAO_FEZ oficial. A decisao oficial permanece em t_ocorrencia.';

CREATE OR REPLACE FUNCTION public.criar_revisao_tarefa_filho_interno(p_token text, p_id_filho_tarefa bigint, p_observacao text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_token_hash text;
  v_pai_id bigint;
  v_filho_id bigint;
  v_vigencia_id bigint;
  v_tarefa_id bigint;
  v_inicio timestamptz;
  v_fim timestamptz;
  v_nome_filho text;
  v_nome_tarefa text;
  v_data date;
  v_observacao text;
  v_ocorrencia_tipo text;
  v_id bigint;
  v_status text;
  v_created_at timestamptz;
  v_resolvido_em timestamptz;
begin
  if p_token is null or p_token !~ '^[0-9a-f]{64}$' then
    return jsonb_build_object('ok', false, 'codigo', 'SESSAO_INVALIDA');
  end if;

  if p_id_filho_tarefa is null or p_id_filho_tarefa <= 0 then
    return jsonb_build_object('ok', false, 'codigo', 'TAREFA_INVALIDA');
  end if;

  v_observacao := nullif(btrim(coalesce(p_observacao, '')), '');
  if v_observacao is not null and char_length(v_observacao) > 120 then
    return jsonb_build_object('ok', false, 'codigo', 'OBSERVACAO_INVALIDA');
  end if;

  v_token_hash := pg_catalog.encode(
    extensions.digest(lower(p_token), 'sha256'),
    'hex'
  );

  select a.id_usuario_pai, a.id_filho
    into v_pai_id, v_filho_id
  from public.t_filho_acesso_app a
  where a.token_hash = v_token_hash
    and a.ativo = true
  limit 1;

  if v_pai_id is null or v_filho_id is null then
    return jsonb_build_object('ok', false, 'codigo', 'SESSAO_INVALIDA');
  end if;

  select ft.id_vigencia, ft.id_tarefa
    into v_vigencia_id, v_tarefa_id
  from public.t_filho_tarefa ft
  where ft.id = p_id_filho_tarefa
    and ft.id_usuario_pai = v_pai_id
    and ft.id_filho = v_filho_id
  for key share;

  if v_vigencia_id is null then
    return jsonb_build_object('ok', false, 'codigo', 'TAREFA_INVALIDA');
  end if;

  select v.data_inicio, v.data_fim
    into v_inicio, v_fim
  from public.t_vigencia v
  where v.id = v_vigencia_id
    and v.id_usuario_pai = v_pai_id
  for key share;

  if v_inicio is null or v_fim is null then
    return jsonb_build_object('ok', false, 'codigo', 'TAREFA_INVALIDA');
  end if;

  if now() < v_inicio or now() > v_fim then
    return jsonb_build_object('ok', false, 'codigo', 'VIGENCIA_INATIVA');
  end if;

  v_data := timezone('America/Sao_Paulo', now())::date;

  if v_data < timezone('America/Sao_Paulo', v_inicio)::date
     or v_data > timezone('America/Sao_Paulo', v_fim)::date then
    return jsonb_build_object('ok', false, 'codigo', 'VIGENCIA_INATIVA');
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(
      p_id_filho_tarefa::text || ':' || v_data::text,
      0
    )
  );

  -- Se o filho ja tinha avisado que terminou antes do NAO_FEZ, nao abre uma segunda contestacao.
  if exists (
    select 1
    from public.t_solicitacao_tarefa_filho s
    where s.id_filho_tarefa = p_id_filho_tarefa
      and s.data_referencia = v_data
  ) then
    return jsonb_build_object('ok', false, 'codigo', 'REVISAO_INDISPONIVEL');
  end if;

  select o.tipo
    into v_ocorrencia_tipo
  from public.t_ocorrencia o
  where o.id_filho_tarefa = p_id_filho_tarefa
    and timezone('America/Sao_Paulo', o.created_at)::date = v_data
  order by o.created_at desc
  limit 1
  for update;

  if v_ocorrencia_tipo is null or v_ocorrencia_tipo <> 'NAO_FEZ' then
    return jsonb_build_object('ok', false, 'codigo', 'REVISAO_INDISPONIVEL');
  end if;

  select f.nome, t.nome
    into v_nome_filho, v_nome_tarefa
  from public.t_filho f
  join public.t_tarefa t
    on t.id = v_tarefa_id
   and t.id_usuario_pai = v_pai_id
  where f.id = v_filho_id
    and f.id_usuario_pai = v_pai_id;

  if v_nome_filho is null or v_nome_tarefa is null then
    return jsonb_build_object('ok', false, 'codigo', 'TAREFA_INVALIDA');
  end if;

  insert into public.t_revisao_tarefa_filho (
    id_filho_tarefa,
    data_referencia,
    observacao
  )
  values (
    p_id_filho_tarefa,
    v_data,
    v_observacao
  )
  on conflict (id_filho_tarefa, data_referencia) do nothing
  returning id, status, created_at, resolvido_em
    into v_id, v_status, v_created_at, v_resolvido_em;

  if v_id is null then
    select r.id, r.status, r.created_at, r.resolvido_em, r.observacao
      into v_id, v_status, v_created_at, v_resolvido_em, v_observacao
    from public.t_revisao_tarefa_filho r
    where r.id_filho_tarefa = p_id_filho_tarefa
      and r.data_referencia = v_data;

    return jsonb_build_object(
      'ok', true,
      'criada', false,
      'id_usuario_pai', v_pai_id,
      'id_filho', v_filho_id,
      'nome_filho', v_nome_filho,
      'nome_tarefa', v_nome_tarefa,
      'revisao', jsonb_build_object(
        'id', v_id,
        'id_filho_tarefa', p_id_filho_tarefa,
        'data_referencia', v_data,
        'observacao', v_observacao,
        'status', v_status,
        'created_at', v_created_at,
        'resolvido_em', v_resolvido_em
      )
    );
  end if;

  update public.t_filho_acesso_app
  set ultimo_acesso_em = now(),
      updated_at = now()
  where token_hash = v_token_hash
    and ativo = true;

  return jsonb_build_object(
    'ok', true,
    'criada', true,
    'id_usuario_pai', v_pai_id,
    'id_filho', v_filho_id,
    'nome_filho', v_nome_filho,
    'nome_tarefa', v_nome_tarefa,
    'revisao', jsonb_build_object(
      'id', v_id,
      'id_filho_tarefa', p_id_filho_tarefa,
      'data_referencia', v_data,
      'observacao', v_observacao,
      'status', v_status,
      'created_at', v_created_at,
      'resolvido_em', v_resolvido_em
    )
  );
end;
$function$;

CREATE OR REPLACE FUNCTION public.resolver_revisao_tarefa_filho(p_id_revisao bigint, p_decisao text)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_pai_id bigint;
  v_id_filho_tarefa bigint;
  v_data date;
  v_status text;
  v_tipo_ocorrencia text;
begin
  select p.id
    into v_pai_id
  from public.t_usuario_pai p
  where p.auth_user_id = auth.uid();

  if v_pai_id is null then
    raise exception 'Responsável não encontrado';
  end if;

  if p_decisao <> 'MANTER_NAO_FEZ' then
    raise exception 'Decisão de revisão inválida';
  end if;

  select r.id_filho_tarefa, r.data_referencia, r.status
    into v_id_filho_tarefa, v_data, v_status
  from public.t_revisao_tarefa_filho r
  join public.t_filho_tarefa ft
    on ft.id = r.id_filho_tarefa
   and ft.id_usuario_pai = v_pai_id
  where r.id = p_id_revisao
  for update of r;

  if v_id_filho_tarefa is null then
    raise exception 'Revisão não encontrada';
  end if;

  if v_status <> 'PENDENTE' then
    return true;
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(
      v_id_filho_tarefa::text || ':' || v_data::text,
      0
    )
  );

  select o.tipo
    into v_tipo_ocorrencia
  from public.t_ocorrencia o
  where o.id_filho_tarefa = v_id_filho_tarefa
    and timezone('America/Sao_Paulo', o.created_at)::date = v_data
  order by o.created_at desc
  limit 1;

  if v_tipo_ocorrencia = 'FEZ' then
    update public.t_revisao_tarefa_filho
    set status = 'ALTERADO_PARA_FEZ',
        resolvido_em = now()
    where id = p_id_revisao
      and status = 'PENDENTE';
    return true;
  end if;

  if v_tipo_ocorrencia is null or v_tipo_ocorrencia <> 'NAO_FEZ' then
    raise exception 'O Não fez original não está mais disponível para manter';
  end if;

  update public.t_revisao_tarefa_filho
  set status = 'MANTEVE_NAO_FEZ',
      resolvido_em = now()
  where id = p_id_revisao
    and status = 'PENDENTE';

  return true;
end;
$function$;

CREATE OR REPLACE FUNCTION public.resolver_revisao_ao_marcar_fez()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_data date;
begin
  if new.tipo <> 'FEZ' then
    return new;
  end if;

  v_data := timezone('America/Sao_Paulo', new.created_at)::date;

  update public.t_revisao_tarefa_filho r
  set status = 'ALTERADO_PARA_FEZ',
      resolvido_em = now()
  where r.id_filho_tarefa = new.id_filho_tarefa
    and r.data_referencia = v_data
    and r.status = 'PENDENTE';

  return new;
end;
$function$;

