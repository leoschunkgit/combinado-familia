-- 0079 - Push de resposta ao filho somente quando o responsavel responde uma interacao iniciada pelo filho.
-- Nao gera push para marcacoes normais de Fez/Nao fez.

create table if not exists public.t_push_resposta_filho (
  id bigint generated by default as identity primary key,
  id_usuario_pai bigint not null references public.t_usuario_pai(id) on delete cascade,
  id_filho bigint not null references public.t_filho(id) on delete cascade,
  tipo_interacao text not null check (tipo_interacao in ('SOLICITACAO', 'REVISAO')),
  id_interacao bigint not null,
  status_resposta text not null,
  notificacoes_enviadas integer not null check (notificacoes_enviadas > 0),
  created_at timestamptz not null default now(),
  constraint t_push_resposta_filho_interacao_unica
    unique (tipo_interacao, id_interacao)
);

create index if not exists idx_push_resposta_filho_pai_filho
  on public.t_push_resposta_filho (id_usuario_pai, id_filho, created_at desc);

alter table public.t_push_resposta_filho enable row level security;

revoke all privileges on table public.t_push_resposta_filho from public, anon, authenticated, service_role;
grant select, insert on table public.t_push_resposta_filho to service_role;

revoke all privileges on sequence public.t_push_resposta_filho_id_seq from public, anon, authenticated, service_role;
grant usage on sequence public.t_push_resposta_filho_id_seq to service_role;

comment on table public.t_push_resposta_filho is
  'Controle idempotente do push enviado ao filho quando o responsavel responde a Terminei ou Pedido de revisao.';
