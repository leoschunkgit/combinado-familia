CREATE OR REPLACE FUNCTION public.admin_adicionar(
  p_email text
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_admin_atual bigint;
  v_usuario public.t_usuario_pai%ROWTYPE;
  v_admin_id bigint;
  v_ja_existia boolean;
BEGIN
  v_admin_atual := public.current_admin_id();
  IF v_admin_atual IS NULL THEN
    RAISE EXCEPTION 'Acesso administrativo não autorizado'
      USING ERRCODE = '42501';
  END IF;

  SELECT p.*
  INTO v_usuario
  FROM public.t_usuario_pai p
  WHERE lower(p.email) = lower(trim(coalesce(p_email, '')))
  LIMIT 1;

  IF v_usuario.id IS NULL THEN
    RAISE EXCEPTION 'Usuário não encontrado. Ele precisa ter uma conta no Combinado Família';
  END IF;

  SELECT EXISTS (
    SELECT 1
    FROM public.t_admin a
    WHERE a.id_usuario_pai = v_usuario.id
  )
  INTO v_ja_existia;

  INSERT INTO public.t_admin (id_usuario_pai, ativo)
  VALUES (v_usuario.id, true)
  ON CONFLICT (id_usuario_pai)
  DO UPDATE SET ativo = true
  RETURNING id INTO v_admin_id;

  PERFORM public.admin_auditar(
    CASE WHEN v_ja_existia THEN 'ADMIN_REATIVADO' ELSE 'ADMIN_ADICIONADO' END,
    'admin',
    v_admin_id::text,
    jsonb_build_object(
      'id_usuario_pai', v_usuario.id,
      'nome', v_usuario.nome,
      'email', v_usuario.email
    )
  );

  RETURN v_admin_id;
END;
$function$;

REVOKE ALL ON FUNCTION public.admin_adicionar(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.admin_adicionar(text) TO authenticated;

CREATE OR REPLACE FUNCTION public.admin_definir_status(
  p_admin_id bigint,
  p_ativo boolean
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_admin_atual bigint;
  v_alvo public.t_admin%ROWTYPE;
  v_ativos integer;
  v_usuario public.t_usuario_pai%ROWTYPE;
BEGIN
  v_admin_atual := public.current_admin_id();
  IF v_admin_atual IS NULL THEN
    RAISE EXCEPTION 'Acesso administrativo não autorizado'
      USING ERRCODE = '42501';
  END IF;

  SELECT a.*
  INTO v_alvo
  FROM public.t_admin a
  WHERE a.id = p_admin_id;

  IF v_alvo.id IS NULL THEN
    RAISE EXCEPTION 'Administrador não encontrado';
  END IF;

  IF p_ativo = false AND v_alvo.ativo = true THEN
    SELECT count(*)
    INTO v_ativos
    FROM public.t_admin
    WHERE ativo = true;

    IF v_ativos <= 1 THEN
      RAISE EXCEPTION 'Não é possível desativar o último administrador ativo';
    END IF;
  END IF;

  SELECT p.*
  INTO v_usuario
  FROM public.t_usuario_pai p
  WHERE p.id = v_alvo.id_usuario_pai;

  UPDATE public.t_admin
  SET ativo = p_ativo
  WHERE id = p_admin_id;

  PERFORM public.admin_auditar(
    CASE WHEN p_ativo THEN 'ADMIN_ATIVADO' ELSE 'ADMIN_DESATIVADO' END,
    'admin',
    p_admin_id::text,
    jsonb_build_object(
      'id_usuario_pai', v_alvo.id_usuario_pai,
      'nome', v_usuario.nome,
      'email', v_usuario.email,
      'ativo_anterior', v_alvo.ativo,
      'ativo_novo', p_ativo
    )
  );

  RETURN true;
END;
$function$;

REVOKE ALL ON FUNCTION public.admin_definir_status(bigint, boolean) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.admin_definir_status(bigint, boolean) TO authenticated;

CREATE OR REPLACE FUNCTION public.admin_auditoria_listar(
  p_limite integer DEFAULT 100
)
RETURNS TABLE (
  id bigint,
  admin_id bigint,
  admin_nome text,
  admin_email text,
  acao text,
  entidade text,
  entidade_id text,
  detalhes jsonb,
  created_at timestamptz
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'Acesso administrativo não autorizado'
      USING ERRCODE = '42501';
  END IF;

  RETURN QUERY
  SELECT
    au.id,
    au.id_admin,
    p.nome,
    p.email,
    au.acao,
    au.entidade,
    au.entidade_id,
    au.detalhes,
    au.created_at
  FROM public.t_admin_auditoria au
  JOIN public.t_admin a ON a.id = au.id_admin
  JOIN public.t_usuario_pai p ON p.id = a.id_usuario_pai
  ORDER BY au.created_at DESC, au.id DESC
  LIMIT greatest(1, least(coalesce(p_limite, 100), 500));
END;
$function$;

