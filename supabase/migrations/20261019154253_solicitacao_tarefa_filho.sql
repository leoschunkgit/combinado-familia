-- Serializa criacao de Fez/Nao fez e aviso do filho para a mesma atribuicao/dia.
-- Impede corrida em que os dois seriam criados simultaneamente.
create or replace function public.serializar_ocorrencia_solicitacao_tarefa_dia()
returns trigger
language plpgsql
set search_path = ''
as $function$
declare
  v_data date;
begin
  v_data := timezone('America/Sao_Paulo', new.created_at)::date;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(
      new.id_filho_tarefa::text || ':' || v_data::text,
      0
    )
  );

  return new;
end;
$function$;

