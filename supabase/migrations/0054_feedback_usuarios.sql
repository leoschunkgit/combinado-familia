CREATE TABLE public.t_feedback (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario_pai bigint NOT NULL REFERENCES public.t_usuario_pai(id) ON DELETE CASCADE,
  tipo text NOT NULL,
  assunto text NOT NULL,
  mensagem text NOT NULL,
  plataforma text NOT NULL,
  version_name text,
  version_code integer,
  pagina_origem text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT t_feedback_tipo_check CHECK (tipo IN ('SUGESTAO', 'PROBLEMA', 'DUVIDA', 'ELOGIO')),
  CONSTRAINT t_feedback_plataforma_check CHECK (plataforma IN ('web', 'android', 'ios')),
  CONSTRAINT t_feedback_assunto_check CHECK (char_length(trim(assunto)) BETWEEN 3 AND 120),
  CONSTRAINT t_feedback_mensagem_check CHECK (char_length(trim(mensagem)) BETWEEN 3 AND 2000),
  CONSTRAINT t_feedback_version_code_check CHECK (version_code IS NULL OR version_code > 0)
);

CREATE INDEX idx_t_feedback_created_at
  ON public.t_feedback (created_at DESC);

CREATE INDEX idx_t_feedback_usuario_created_at
  ON public.t_feedback (id_usuario_pai, created_at DESC);

CREATE INDEX idx_t_feedback_tipo_created_at
  ON public.t_feedback (tipo, created_at DESC);

ALTER TABLE public.t_feedback ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.t_feedback FROM anon, authenticated;

CREATE OR REPLACE FUNCTION public.enviar_feedback(
  p_tipo text,
  p_assunto text,
  p_mensagem text,
  p_plataforma text,
  p_version_name text DEFAULT NULL,
  p_version_code integer DEFAULT NULL,
  p_pagina_origem text DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_pai_id bigint;
  v_id bigint;
  v_tipo text;
  v_plataforma text;
  v_assunto text;
  v_mensagem text;
BEGIN
  v_pai_id := public.current_pai_id();
  IF v_pai_id IS NULL THEN
    RAISE EXCEPTION 'Usuário responsável não identificado'
      USING ERRCODE = '42501';
  END IF;

  v_tipo := upper(trim(coalesce(p_tipo, '')));
  IF v_tipo NOT IN ('SUGESTAO', 'PROBLEMA', 'DUVIDA', 'ELOGIO') THEN
    RAISE EXCEPTION 'Tipo de feedback inválido';
  END IF;

  v_plataforma := lower(trim(coalesce(p_plataforma, '')));
  IF v_plataforma NOT IN ('web', 'android', 'ios') THEN
    RAISE EXCEPTION 'Plataforma inválida';
  END IF;

  v_assunto := trim(coalesce(p_assunto, ''));
  IF char_length(v_assunto) < 3 OR char_length(v_assunto) > 120 THEN
    RAISE EXCEPTION 'O assunto deve ter entre 3 e 120 caracteres';
  END IF;

  v_mensagem := trim(coalesce(p_mensagem, ''));
  IF char_length(v_mensagem) < 3 OR char_length(v_mensagem) > 2000 THEN
    RAISE EXCEPTION 'A mensagem deve ter entre 3 e 2000 caracteres';
  END IF;

  IF p_version_code IS NOT NULL AND p_version_code <= 0 THEN
    RAISE EXCEPTION 'Código da versão inválido';
  END IF;

  INSERT INTO public.t_feedback (
    id_usuario_pai,
    tipo,
    assunto,
    mensagem,
    plataforma,
    version_name,
    version_code,
    pagina_origem
  )
  VALUES (
    v_pai_id,
    v_tipo,
    v_assunto,
    v_mensagem,
    v_plataforma,
    nullif(trim(coalesce(p_version_name, '')), ''),
    p_version_code,
    nullif(left(trim(coalesce(p_pagina_origem, '')), 300), '')
  )
  RETURNING id INTO v_id;

  RETURN v_id;
END;
$function$;

REVOKE ALL ON FUNCTION public.enviar_feedback(text, text, text, text, text, integer, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.enviar_feedback(text, text, text, text, text, integer, text) TO authenticated;

CREATE OR REPLACE FUNCTION public.admin_feedbacks(p_limite integer DEFAULT 300)
RETURNS TABLE (
  id bigint,
  id_usuario_pai bigint,
  usuario_nome text,
  usuario_email text,
  tipo text,
  assunto text,
  mensagem text,
  plataforma text,
  version_name text,
  version_code integer,
  pagina_origem text,
  created_at timestamptz
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_limite integer;
BEGIN
  IF public.current_admin_id() IS NULL THEN
    RAISE EXCEPTION 'Acesso administrativo não autorizado'
      USING ERRCODE = '42501';
  END IF;

  v_limite := LEAST(GREATEST(coalesce(p_limite, 300), 1), 500);

  RETURN QUERY
  SELECT
    f.id,
    f.id_usuario_pai,
    u.nome::text,
    u.email::text,
    f.tipo,
    f.assunto,
    f.mensagem,
    f.plataforma,
    f.version_name,
    f.version_code,
    f.pagina_origem,
    f.created_at
  FROM public.t_feedback f
  JOIN public.t_usuario_pai u ON u.id = f.id_usuario_pai
  ORDER BY f.created_at DESC, f.id DESC
  LIMIT v_limite;
END;
$function$;

REVOKE ALL ON FUNCTION public.admin_feedbacks(integer) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.admin_feedbacks(integer) TO authenticated;
