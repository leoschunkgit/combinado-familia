-- 0069 - Push de pendencias exclusivo do app do filho.
-- Mantem completamente separadas as tabelas e o controle idempotente do push do responsavel.
-- O Firebase e o segredo do cron sao infraestrutura compartilhada, mas tokens e envios nao sao.

create table if not exists public.t_push_dispositivo_filho (
  id bigint generated by default as identity primary key,
  id_usuario_pai bigint not null references public.t_usuario_pai(id) on delete cascade,
  id_filho bigint not null references public.t_filho(id) on delete cascade,
  id_acesso_app_filho bigint not null references public.t_filho_acesso_app(id) on delete cascade,
  token text not null unique,
  plataforma text not null check (plataforma in ('android', 'ios')),
  ativo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_push_dispositivo_filho_acesso_ativo
  on public.t_push_dispositivo_filho (id_acesso_app_filho, ativo);

create index if not exists idx_push_dispositivo_filho_filho_ativo
  on public.t_push_dispositivo_filho (id_usuario_pai, id_filho, ativo);

alter table public.t_push_dispositivo_filho enable row level security;

create table if not exists public.t_push_envio_filho (
  id bigint generated by default as identity primary key,
  id_push_dispositivo_filho bigint not null references public.t_push_dispositivo_filho(id) on delete cascade,
  id_usuario_pai bigint not null references public.t_usuario_pai(id) on delete cascade,
  id_filho bigint not null references public.t_filho(id) on delete cascade,
  data_referencia date not null,
  janela_envio text not null check (janela_envio in ('09:00', '12:00', '19:00')),
  qtd_pendencias integer not null check (qtd_pendencias > 0),
  created_at timestamptz not null default now(),
  constraint t_push_envio_filho_unico_por_aparelho_dia_janela
    unique (id_push_dispositivo_filho, data_referencia, janela_envio)
);

create index if not exists idx_push_envio_filho_pai_data
  on public.t_push_envio_filho (id_usuario_pai, data_referencia);

alter table public.t_push_envio_filho enable row level security;

revoke all privileges on table public.t_push_dispositivo_filho from public, anon, authenticated, service_role;
revoke all privileges on table public.t_push_envio_filho from public, anon, authenticated, service_role;

grant select, insert, update on table public.t_push_dispositivo_filho to service_role;
grant select, insert on table public.t_push_envio_filho to service_role;

revoke all privileges on sequence public.t_push_dispositivo_filho_id_seq from public, anon, authenticated, service_role;
revoke all privileges on sequence public.t_push_envio_filho_id_seq from public, anon, authenticated, service_role;

grant usage on sequence public.t_push_dispositivo_filho_id_seq to service_role;
grant usage on sequence public.t_push_envio_filho_id_seq to service_role;

comment on table public.t_push_dispositivo_filho is
  'Tokens push exclusivos de acessos ativos do app do filho. Nao reutiliza a tabela do responsavel.';

comment on table public.t_push_envio_filho is
  'Controle idempotente dos avisos de tarefas pendentes enviados ao app do filho.';

create or replace function public.desativar_push_filho_ao_revogar_acesso()
returns trigger
language plpgsql
security definer
set search_path to ''
as $function$
begin
  if old.ativo = true and new.ativo = false then
    update public.t_push_dispositivo_filho
    set ativo = false,
        updated_at = now()
    where id_acesso_app_filho = new.id
      and ativo = true;
  end if;

  return new;
end;
$function$;

revoke all on function public.desativar_push_filho_ao_revogar_acesso() from public, anon, authenticated, service_role;

drop trigger if exists desativar_push_filho_ao_revogar_acesso
  on public.t_filho_acesso_app;

create trigger desativar_push_filho_ao_revogar_acesso
after update of ativo on public.t_filho_acesso_app
for each row
when (old.ativo is distinct from new.ativo)
execute function public.desativar_push_filho_ao_revogar_acesso();

create extension if not exists pg_cron with schema pg_catalog;
create extension if not exists pg_net with schema extensions;

do $$
declare
  v_job_id bigint;
  v_job_name text;
begin
  foreach v_job_name in array array[
    'push-filho-pendencias-0900-sao-paulo',
    'push-filho-pendencias-1200-sao-paulo',
    'push-filho-pendencias-1900-sao-paulo'
  ]
  loop
    select jobid into v_job_id
    from cron.job
    where jobname = v_job_name
    limit 1;

    if v_job_id is not null then
      perform cron.unschedule(v_job_id);
    end if;

    v_job_id := null;
  end loop;
end
$$;

