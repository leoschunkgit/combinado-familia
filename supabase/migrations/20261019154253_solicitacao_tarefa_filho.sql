-- 0071 - Aviso imutavel do filho de que concluiu uma tarefa.
--
-- Fonte unica de verdade:
-- - a solicitacao guarda somente id_filho_tarefa + data + observacao;
-- - filho, tarefa, responsavel e vigencia sao sempre derivados de t_filho_tarefa;
-- - o estado pendente/resolvido NAO e salvo: e derivado da existencia de t_ocorrencia;
-- - estrelas continuam sendo geradas exclusivamente por t_ocorrencia.tipo = 'FEZ'.
--
-- A solicitacao e criada somente por RPC interna validada pela sessao do app do filho.
-- O link publico do filho permanece fora deste fluxo.

create table if not exists public.t_solicitacao_tarefa_filho (
  id bigint generated by default as identity primary key,
  id_filho_tarefa bigint not null
    references public.t_filho_tarefa(id) on delete cascade,
  data_referencia date not null,
  observacao text null,
  created_at timestamptz not null default now(),
  constraint t_solicitacao_tarefa_filho_observacao_chk
    check (
      observacao is null
      or (
        char_length(btrim(observacao)) between 1 and 120
        and observacao = btrim(observacao)
      )
    ),
  constraint t_solicitacao_tarefa_filho_unica_tarefa_dia
    unique (id_filho_tarefa, data_referencia)
);

create index if not exists idx_solicitacao_tarefa_filho_data
  on public.t_solicitacao_tarefa_filho (data_referencia, id_filho_tarefa);

alter table public.t_solicitacao_tarefa_filho enable row level security;

revoke all privileges on table public.t_solicitacao_tarefa_filho
from public, anon, authenticated, service_role;

revoke all privileges on sequence public.t_solicitacao_tarefa_filho_id_seq
from public, anon, authenticated, service_role;

grant select on table public.t_solicitacao_tarefa_filho to authenticated;

drop policy if exists solicitacao_tarefa_filho_select_responsavel
  on public.t_solicitacao_tarefa_filho;

create policy solicitacao_tarefa_filho_select_responsavel
on public.t_solicitacao_tarefa_filho
for select
to authenticated
using (
  exists (
    select 1
    from public.t_filho_tarefa ft
    where ft.id = t_solicitacao_tarefa_filho.id_filho_tarefa
      and ft.id_usuario_pai = public.current_pai_id()
  )
);

comment on table public.t_solicitacao_tarefa_filho is
