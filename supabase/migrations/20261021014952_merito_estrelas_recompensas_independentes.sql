
-- Estrelas como mérito permanente e recompensas com progresso independente.
-- Regras centrais:
-- 1. Uma tarefa do filho em uma vigência/data pode conceder no máximo 1 estrela.
-- 2. A estrela concedida nunca é retirada por Não fez, edição ou exclusão posterior.
-- 3. Resgatar/cancelar/entregar recompensa não altera o total de estrelas.
-- 4. Cada recompensa tem progresso próprio por filho.
-- 5. Só um resgate pendente da mesma recompensa pode existir por vez.
-- 6. A entrega confirma o marco do próximo ciclo usando o total no momento do resgate.
-- 7. Alterações na meta valem imediatamente enquanto não houve resgate e, após resgate,
--    somente para os ciclos seguintes; o resgate guarda snapshot da meta.

create table if not exists public.t_estrela_concessao (
  id bigint generated by default as identity primary key,
  id_usuario_pai bigint not null references public.t_usuario_pai(id) on delete cascade,
  id_filho bigint not null references public.t_filho(id) on delete cascade,
  id_vigencia bigint not null,
  id_tarefa bigint not null,
  id_filho_tarefa_origem bigint null,
  id_ocorrencia_origem bigint null,
  tarefa_nome_snapshot text null,
  data_referencia date not null,
  created_at timestamptz not null default now(),
  constraint t_estrela_concessao_ids_chk check (
    id_usuario_pai > 0 and id_filho > 0 and id_vigencia > 0 and id_tarefa > 0
  ),
  constraint t_estrela_concessao_origem_chk check (
    id_filho_tarefa_origem is null or id_filho_tarefa_origem > 0
  ),
  constraint t_estrela_concessao_ocorrencia_chk check (
    id_ocorrencia_origem is null or id_ocorrencia_origem > 0
  ),
  constraint t_estrela_concessao_logica_uniq
    unique (id_usuario_pai, id_filho, id_vigencia, id_tarefa, data_referencia)
);

create unique index if not exists t_estrela_concessao_ocorrencia_uniq
  on public.t_estrela_concessao(id_ocorrencia_origem)
  where id_ocorrencia_origem is not null;

create index if not exists t_estrela_concessao_filho_idx
  on public.t_estrela_concessao(id_usuario_pai, id_filho, created_at desc);

create index if not exists t_estrela_concessao_vigencia_idx
  on public.t_estrela_concessao(id_usuario_pai, id_filho, id_vigencia, data_referencia);

alter table public.t_estrela_concessao enable row level security;

drop policy if exists estrela_concessao_select_propria on public.t_estrela_concessao;
create policy estrela_concessao_select_propria
on public.t_estrela_concessao
for select
to authenticated
using (
  exists (
    select 1
    from public.t_usuario_pai p
    where p.id = t_estrela_concessao.id_usuario_pai
      and p.auth_user_id = auth.uid()
  )
);

revoke all on public.t_estrela_concessao from public, anon, authenticated;
grant select on public.t_estrela_concessao to authenticated;

alter table public.t_recompensa_resgate
  add column if not exists meta_estrelas_no_resgate integer null,
  add column if not exists total_estrelas_no_resgate integer null;

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 't_recompensa_resgate_meta_snapshot_chk'
      and conrelid = 'public.t_recompensa_resgate'::regclass
  ) then
    alter table public.t_recompensa_resgate
      add constraint t_recompensa_resgate_meta_snapshot_chk
      check (meta_estrelas_no_resgate is null or meta_estrelas_no_resgate between 1 and 100000);
  end if;

  if not exists (
    select 1
    from pg_constraint
    where conname = 't_recompensa_resgate_total_snapshot_chk'
      and conrelid = 'public.t_recompensa_resgate'::regclass
  ) then
    alter table public.t_recompensa_resgate
      add constraint t_recompensa_resgate_total_snapshot_chk
      check (total_estrelas_no_resgate is null or total_estrelas_no_resgate >= 0);
  end if;
end
$$;

create unique index if not exists t_recompensa_resgate_pendente_uniq
  on public.t_recompensa_resgate(id_usuario_pai, id_filho, id_recompensa)
  where status = 'PENDENTE';

create or replace function public.estrelas_total_conquistado_interno(
  p_id_usuario_pai bigint,
  p_id_filho bigint
)
returns integer
language sql
stable
security definer
set search_path = ''
as $function$
  select count(*)::integer
  from public.t_estrela_concessao c
  where c.id_usuario_pai = p_id_usuario_pai
    and c.id_filho = p_id_filho;
$function$;

