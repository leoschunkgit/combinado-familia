create table if not exists billing.assinatura_evento (
  id bigint generated by default as identity primary key,
  id_assinatura bigint references billing.assinatura(id) on delete set null,
  provedor text not null,
  evento_externo_id text,
  tipo text not null,
  ocorrido_em timestamptz not null default now(),
  payload jsonb not null default '{}'::jsonb,
  processado_em timestamptz,
  erro_processamento text,
  created_at timestamptz not null default now(),
  constraint assinatura_evento_provedor_chk check (
    provedor ~ '^[A-Z][A-Z0-9_]*$'
  ),
  constraint assinatura_evento_tipo_chk check (
    tipo ~ '^[A-Z][A-Z0-9_.-]*$'
  )
);

create unique index if not exists ux_billing_evento_externo
  on billing.assinatura_evento (provedor, evento_externo_id)
  where evento_externo_id is not null;

create index if not exists ix_billing_evento_assinatura_ocorrido
  on billing.assinatura_evento (id_assinatura, ocorrido_em desc);

create table if not exists billing.direito_override (
  id bigint generated by default as identity primary key,
  id_usuario_pai bigint references public.t_usuario_pai(id) on delete set null,
  id_recurso bigint not null references billing.recurso(id) on delete cascade,
  valor jsonb not null,
  origem text not null,
  motivo text,
  inicio_em timestamptz not null default now(),
  fim_em timestamptz,
  ativo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint direito_override_origem_chk check (
    origem ~ '^[A-Z][A-Z0-9_]*$'
  ),
  constraint direito_override_periodo_chk check (
    fim_em is null or fim_em > inicio_em
  ),
  constraint direito_override_valor_chk check (
    jsonb_typeof(valor) is not null and jsonb_typeof(valor) <> 'null'
