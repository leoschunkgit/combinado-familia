-- Núcleo isolado de planos, assinaturas e direitos.
-- Fase 1: infraestrutura somente. Nenhuma regra do app existente consulta este schema.
-- O schema billing não é exposto ao cliente e não concede acesso a anon/authenticated.

create schema if not exists billing;

comment on schema billing is
  'Domínio interno de planos, ofertas, assinaturas, eventos de cobrança e direitos do Combinado Família.';

revoke all on schema billing from public, anon, authenticated;

create table if not exists billing.plano (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  nome text not null,
  descricao text,
  prioridade integer not null default 0,
  padrao boolean not null default false,
  ativo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint plano_codigo_chk check (codigo ~ '^[A-Z][A-Z0-9_]*$')
);

create unique index if not exists ux_billing_plano_padrao
  on billing.plano ((padrao))
  where padrao = true;

create table if not exists billing.recurso (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  nome text not null,
  descricao text,
  tipo text not null,
  ativo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint recurso_codigo_chk check (codigo ~ '^[A-Z][A-Z0-9_.-]*$'),
  constraint recurso_tipo_chk check (
    tipo in ('BOOLEANO','LIMITE_INTEIRO','NUMERO','TEXTO','JSON')
  )
);

create table if not exists billing.plano_recurso (
  id_plano bigint not null references billing.plano(id) on delete cascade,
  id_recurso bigint not null references billing.recurso(id) on delete cascade,
  valor jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (id_plano, id_recurso),
  constraint plano_recurso_valor_chk check (
    jsonb_typeof(valor) is not null and jsonb_typeof(valor) <> 'null'
  )
);

create index if not exists ix_billing_plano_recurso_recurso
  on billing.plano_recurso (id_recurso);

create table if not exists billing.oferta (
  id bigint generated by default as identity primary key,
  id_plano bigint not null references billing.plano(id),
  codigo text not null unique,
  nome text not null,
  provedor text not null,
  produto_externo_id text,
  base_plan_externo_id text,
  offer_externo_id text,
  periodicidade text not null,
  moeda char(3),
  valor_centavos bigint,
  periodo_teste_dias integer,
  ativo boolean not null default true,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint oferta_codigo_chk check (codigo ~ '^[A-Z][A-Z0-9_.-]*$'),
  constraint oferta_provedor_chk check (provedor ~ '^[A-Z][A-Z0-9_]*$'),
  constraint oferta_periodicidade_chk check (
    periodicidade in ('MENSAL','ANUAL','VITALICIO','PERSONALIZADO')
  ),
  constraint oferta_valor_chk check (
    valor_centavos is null or valor_centavos >= 0
  ),
  constraint oferta_teste_chk check (
    periodo_teste_dias is null or periodo_teste_dias >= 0
  )
);

create index if not exists ix_billing_oferta_plano
  on billing.oferta (id_plano);

create unique index if not exists ux_billing_oferta_provedor_produto
  on billing.oferta (
    provedor,
    produto_externo_id,
    coalesce(base_plan_externo_id,''),
    coalesce(offer_externo_id,'')
  )
  where produto_externo_id is not null;

create table if not exists billing.assinatura (
  id bigint generated by default as identity primary key,
  id_usuario_pai bigint references public.t_usuario_pai(id) on delete set null,
  id_plano bigint not null references billing.plano(id),
  status text not null,
  origem text not null,
  inicio_em timestamptz not null default now(),
  periodo_inicio_em timestamptz,
  periodo_fim_em timestamptz,
  teste_fim_em timestamptz,
  cancelada_em timestamptz,
  encerrada_em timestamptz,
  renovacao_automatica boolean not null default true,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint assinatura_status_chk check (
    status in (
      'EM_TESTE',
      'ATIVA',
      'GRACE_PERIOD',
      'PAGAMENTO_PENDENTE',
      'PAUSADA',
      'CANCELADA',
      'EXPIRADA',
      'REVOGADA'
    )
  ),
  constraint assinatura_origem_chk check (origem ~ '^[A-Z][A-Z0-9_]*$'),
  constraint assinatura_periodo_chk check (
    periodo_fim_em is null
    or periodo_inicio_em is null
    or periodo_fim_em > periodo_inicio_em
  )
);

create index if not exists ix_billing_assinatura_usuario
  on billing.assinatura (id_usuario_pai);

create index if not exists ix_billing_assinatura_plano
  on billing.assinatura (id_plano);

create index if not exists ix_billing_assinatura_status_periodo
  on billing.assinatura (status, periodo_fim_em);

create table if not exists billing.assinatura_provedor (
  id bigint generated by default as identity primary key,
  id_assinatura bigint not null references billing.assinatura(id) on delete cascade,
  id_oferta bigint references billing.oferta(id) on delete set null,
  provedor text not null,
  cliente_externo_id text,
  assinatura_externa_id text,
  produto_externo_id text,
  purchase_token text,
  ultimo_payload jsonb,
  sincronizado_em timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint assinatura_provedor_codigo_chk check (
    provedor ~ '^[A-Z][A-Z0-9_]*$'
  )
);

alter table billing.assinatura_provedor
  add column if not exists id_oferta bigint references billing.oferta(id) on delete set null;

create index if not exists ix_billing_assinatura_provedor_assinatura
  on billing.assinatura_provedor (id_assinatura);

create index if not exists ix_billing_assinatura_provedor_oferta
  on billing.assinatura_provedor (id_oferta);

create unique index if not exists ux_billing_assinatura_provedor_externa
  on billing.assinatura_provedor (provedor, assinatura_externa_id)
  where assinatura_externa_id is not null;

