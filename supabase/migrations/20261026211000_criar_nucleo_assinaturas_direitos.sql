create or replace function billing.plano_efetivo(
  p_id_usuario_pai bigint,
  p_momento timestamptz default now()
)
returns table (
  id_plano bigint,
  codigo text,
  nome text,
  origem text,
  id_assinatura bigint
)
language sql
stable
security invoker
set search_path = billing, public, pg_temp
as $$
  with assinatura_valida as (
    select
      p.id as id_plano,
      p.codigo,
      p.nome,
      a.origem,
      a.id as id_assinatura,
      p.prioridade,
      a.inicio_em
    from billing.assinatura a
    join billing.plano p
      on p.id = a.id_plano
    where a.id_usuario_pai = p_id_usuario_pai
      and p.ativo = true
      and a.status in ('EM_TESTE','ATIVA','GRACE_PERIOD')
      and a.inicio_em <= p_momento
      and (
        a.periodo_fim_em is null
        or a.periodo_fim_em > p_momento
      )
      and (
        a.encerrada_em is null
        or a.encerrada_em > p_momento
      )
    order by
      p.prioridade desc,
      a.inicio_em desc,
      a.id desc
    limit 1
  ),
  plano_padrao as (
    select
      p.id as id_plano,
      p.codigo,
      p.nome,
      'SISTEMA'::text as origem,
      null::bigint as id_assinatura,
      p.prioridade,
      null::timestamptz as inicio_em
    from billing.plano p
    where p.padrao = true
      and p.ativo = true
    order by p.prioridade desc, p.id
    limit 1
  )
  select
    id_plano,
    codigo,
    nome,
    origem,
    id_assinatura
  from (
    select *, 0 as ordem
    from assinatura_valida

    union all

    select *, 1 as ordem
    from plano_padrao
  ) x
  order by ordem
  limit 1;
$$;

create or replace function billing.direitos_efetivos(
  p_id_usuario_pai bigint,
  p_momento timestamptz default now()
)
returns jsonb
language sql
stable
security invoker
set search_path = billing, public, pg_temp
as $$
  with pe as (
    select *
    from billing.plano_efetivo(p_id_usuario_pai, p_momento)
  ),
  do_plano as (
    select
      r.codigo,
      pr.valor,
      1 as precedencia
    from pe
    join billing.plano_recurso pr
      on pr.id_plano = pe.id_plano
    join billing.recurso r
      on r.id = pr.id_recurso
    where r.ativo = true
  ),
  overrides as (
    select distinct on (r.codigo)
      r.codigo,
      o.valor,
      2 as precedencia
    from billing.direito_override o
    join billing.recurso r
      on r.id = o.id_recurso
    where o.id_usuario_pai = p_id_usuario_pai
      and o.ativo = true
      and r.ativo = true
      and o.inicio_em <= p_momento
      and (
        o.fim_em is null
        or o.fim_em > p_momento
      )
    order by
      r.codigo,
      o.inicio_em desc,
      o.id desc
  ),
  combinados as (
    select *
    from do_plano

    union all

    select *
    from overrides
  ),
  escolhidos as (
    select distinct on (codigo)
      codigo,
      valor
    from combinados
    order by
      codigo,
      precedencia desc
  )
  select coalesce(
    jsonb_object_agg(codigo, valor order by codigo),
    '{}'::jsonb
  )
  from escolhidos;
$$;

revoke all on function billing.plano_efetivo(bigint, timestamptz)
  from public, anon, authenticated;

revoke all on function billing.direitos_efetivos(bigint, timestamptz)
  from public, anon, authenticated;
