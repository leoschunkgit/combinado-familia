create or replace function public.registrar_movimento_estrela_ocorrencia()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_pai_id bigint;
  v_filho_id bigint;
  v_vigencia_id bigint;
  v_tarefa_id bigint;
  v_tarefa_nome text;
  v_data date;
  v_pai_antigo bigint;
  v_filho_antigo bigint;
  v_vigencia_antiga bigint;
  v_tarefa_antiga bigint;
  v_tarefa_nome_antiga text;
begin
  if tg_op in ('UPDATE', 'DELETE') and old.tipo = 'FEZ' then
    select
      ft.id_usuario_pai,
      ft.id_filho,
      ft.id_vigencia,
      ft.id_tarefa,
      t.nome
    into
      v_pai_antigo,
      v_filho_antigo,
      v_vigencia_antiga,
      v_tarefa_antiga,
      v_tarefa_nome_antiga
    from public.t_filho_tarefa ft
    left join public.t_tarefa t
      on t.id = ft.id_tarefa
     and t.id_usuario_pai = ft.id_usuario_pai
    where ft.id = old.id_filho_tarefa;

    if v_filho_antigo is null then
      select
        m.id_usuario_pai,
        m.id_filho,
        m.id_vigencia,
        m.id_tarefa,
        m.descricao
      into
        v_pai_antigo,
        v_filho_antigo,
        v_vigencia_antiga,
        v_tarefa_antiga,
        v_tarefa_nome_antiga
      from public.t_estrela_movimento m
      where m.id_ocorrencia = old.id
        and m.tipo in ('FEZ', 'ESTORNO_FEZ')
      order by m.id desc
      limit 1;
    end if;
  end if;

  if tg_op in ('INSERT', 'UPDATE') and new.tipo = 'FEZ' then
    select
      ft.id_usuario_pai,
      ft.id_filho,
      ft.id_vigencia,
      ft.id_tarefa,
      t.nome
    into
      v_pai_id,
      v_filho_id,
      v_vigencia_id,
      v_tarefa_id,
      v_tarefa_nome
    from public.t_filho_tarefa ft
    left join public.t_tarefa t
      on t.id = ft.id_tarefa
     and t.id_usuario_pai = ft.id_usuario_pai
    where ft.id = new.id_filho_tarefa;
  end if;

  if tg_op = 'INSERT' then
    if new.tipo = 'FEZ' and v_filho_id is not null then
      v_data := timezone('America/Sao_Paulo', new.created_at)::date;
      insert into public.t_estrela_movimento (
        id_usuario_pai, id_filho, id_vigencia, id_tarefa,
        id_ocorrencia, tipo, quantidade, descricao, data_referencia
      )
      values (
        v_pai_id, v_filho_id, v_vigencia_id, v_tarefa_id,
        new.id, 'FEZ', 1, v_tarefa_nome, v_data
      );
    end if;
    return new;
  end if;

  if tg_op = 'UPDATE' then
    if old.tipo = 'FEZ' and new.tipo <> 'FEZ' and v_filho_antigo is not null then
      v_data := timezone('America/Sao_Paulo', old.created_at)::date;
      insert into public.t_estrela_movimento (
        id_usuario_pai, id_filho, id_vigencia, id_tarefa,
        id_ocorrencia, tipo, quantidade, descricao, data_referencia
      )
      values (
        v_pai_antigo, v_filho_antigo, v_vigencia_antiga, v_tarefa_antiga,
        old.id, 'ESTORNO_FEZ', -1, v_tarefa_nome_antiga, v_data
      );
    elsif old.tipo <> 'FEZ' and new.tipo = 'FEZ' and v_filho_id is not null then
      v_data := timezone('America/Sao_Paulo', new.created_at)::date;
      insert into public.t_estrela_movimento (
        id_usuario_pai, id_filho, id_vigencia, id_tarefa,
        id_ocorrencia, tipo, quantidade, descricao, data_referencia
      )
      values (
        v_pai_id, v_filho_id, v_vigencia_id, v_tarefa_id,
        new.id, 'FEZ', 1, v_tarefa_nome, v_data
      );
    elsif old.tipo = 'FEZ'
      and new.tipo = 'FEZ'
      and old.id_filho_tarefa is distinct from new.id_filho_tarefa then

      if v_filho_antigo is not null then
        insert into public.t_estrela_movimento (
          id_usuario_pai, id_filho, id_vigencia, id_tarefa,
          id_ocorrencia, tipo, quantidade, descricao, data_referencia
        )
        values (
          v_pai_antigo, v_filho_antigo, v_vigencia_antiga, v_tarefa_antiga,
          old.id, 'ESTORNO_FEZ', -1, v_tarefa_nome_antiga,
          timezone('America/Sao_Paulo', old.created_at)::date
        );
      end if;

      if v_filho_id is not null then
        insert into public.t_estrela_movimento (
          id_usuario_pai, id_filho, id_vigencia, id_tarefa,
          id_ocorrencia, tipo, quantidade, descricao, data_referencia
        )
        values (
          v_pai_id, v_filho_id, v_vigencia_id, v_tarefa_id,
          new.id, 'FEZ', 1, v_tarefa_nome,
          timezone('America/Sao_Paulo', new.created_at)::date
        );
      end if;
    end if;

    return new;
  end if;

  if tg_op = 'DELETE' then
    if old.tipo = 'FEZ' and v_filho_antigo is not null then
      v_data := timezone('America/Sao_Paulo', old.created_at)::date;
      insert into public.t_estrela_movimento (
        id_usuario_pai, id_filho, id_vigencia, id_tarefa,
        id_ocorrencia, tipo, quantidade, descricao, data_referencia
      )
      values (
        v_pai_antigo, v_filho_antigo, v_vigencia_antiga, v_tarefa_antiga,
        old.id, 'ESTORNO_FEZ', -1, v_tarefa_nome_antiga, v_data
      );
    end if;
    return old;
  end if;

  return null;
end;
$function$;

